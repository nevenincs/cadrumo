"""Stream A citation audit for generated schema modules (wave 117).

Every ``modelo_{n}_{year}.py`` module that is GENERATED from a
JSON fixture must carry a provenance block in its docstring
citing:

1. The AEAT Orden ministerial (e.g. ``Orden HAC/819/2024``).
2. The BOE-ID (e.g. ``BOE-A-2024-16129``).
3. The DR xlsx filename (e.g. ``DR303e24.xlsx``).

The xlsx filename must follow AEAT's canonical naming convention
``DR{modelo}e{YY}.xlsx`` where ``YY`` is the 2-digit ejercicio
tail — otherwise a reviewer cannot mechanically locate the source
document AEAT published. The year in the Orden and BOE-ID must
also match the ejercicio so a typo can't silently mis-cite an
unrelated year's document.

Clone modules (e.g. modelo_303_2025 that re-exports 2024's
ENVELOPE) are intentionally not generated; they live with a
hand-authored docstring explaining the clone relationship and
are excluded from this audit by module selection.

Stream A perpetual — any future-generator change that drops or
corrupts the provenance block fails here before it reaches a
compliance audit.
"""

from __future__ import annotations

import re
from types import ModuleType

import pytest

from . import modelo_303_2024

pytestmark = [pytest.mark.unit, pytest.mark.domain_local_state]


_ORDEN_RE = re.compile(r"Orden\s+[A-Z]{2,4}/\d+/\d{4}")
_BOE_ID_RE = re.compile(r"BOE-A-\d{4}-\d+")
_XLSX_RE = re.compile(r"DR(\d{3})e(\d{2})(?:v\d+)?\.xlsx", re.IGNORECASE)


def _extract(pattern: re.Pattern[str], text: str) -> list[str]:
    return pattern.findall(text) if pattern.groups == 0 else [m.group(0) for m in pattern.finditer(text)]


class TestProvenanceCitations:
    @pytest.mark.parametrize(
        "module, expected_modelo, expected_ejercicio",
        [(modelo_303_2024, "303", "2024")],
        ids=lambda v: str(v) if not isinstance(v, ModuleType) else v.__name__.rsplit(".", 1)[-1],
    )
    def test_module_docstring_carries_provenance(
        self,
        module: ModuleType,
        expected_modelo: str,
        expected_ejercicio: str,
    ) -> None:
        """Every generator-emitted module must cite Orden + BOE-ID + xlsx."""
        doc = module.__doc__ or ""
        assert "Generated by aeat.submission._formats._generate" in doc, (
            f"{module.__name__}: missing 'Generated by' provenance header."
        )

        orden_hits = _extract(_ORDEN_RE, doc)
        assert orden_hits, f"{module.__name__}: no 'Orden XXX/NNN/YYYY' citation."

        boe_hits = _extract(_BOE_ID_RE, doc)
        assert boe_hits, f"{module.__name__}: no 'BOE-A-YYYY-NNNNN' citation."

        xlsx_match = _XLSX_RE.search(doc)
        assert xlsx_match, f"{module.__name__}: no 'DR{{modelo}}e{{YY}}.xlsx' citation."

        xlsx_modelo, xlsx_yy = xlsx_match.group(1), xlsx_match.group(2)
        assert xlsx_modelo == expected_modelo, (
            f"{module.__name__}: xlsx filename says modelo {xlsx_modelo!r}, module is for {expected_modelo!r}."
        )
        assert xlsx_yy == expected_ejercicio[-2:], (
            f"{module.__name__}: xlsx filename ejercicio tail {xlsx_yy!r} does not "
            f"match expected {expected_ejercicio[-2:]!r}."
        )

    def test_303_2024_orden_and_boe_agree_on_year(self) -> None:
        """The Orden and BOE-ID must cite the same year so a typo can't
        silently mis-cite an unrelated year's publication."""
        doc = modelo_303_2024.__doc__ or ""
        orden_match = re.search(r"Orden\s+[A-Z]{2,4}/(\d+)/(\d{4})", doc)
        boe_match = re.search(r"BOE-A-(\d{4})-\d+", doc)
        assert orden_match and boe_match
        assert orden_match.group(2) == boe_match.group(1), (
            f"Orden year {orden_match.group(2)} != BOE-ID year {boe_match.group(1)} in {modelo_303_2024.__name__}."
        )

    def test_303_2024_cites_expected_orden(self) -> None:
        """Lock the specific Orden + BOE-ID so a regeneration pointed at the
        wrong fixture can't silently rewrite the provenance to a different
        legal basis."""
        doc = modelo_303_2024.__doc__ or ""
        assert "Orden HAC/819/2024" in doc
        assert "BOE-A-2024-16129" in doc
