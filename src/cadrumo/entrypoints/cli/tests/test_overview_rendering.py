"""Tests for the operator-facing ``overview status`` text and notice projection.

These pin three things. The next-step guidance must reflect the actual
workspace state rather than always saying "import a bank file" (M19). The
draft / work-unit distinction must read unmistakably so an operator with work
units never thinks their work was lost. And - the reason the guidance was
rebuilt as typed actions - the text surface and the JSON envelope must state
forward guidance from ONE resolved projection, never from two independently
derived strings.

The executable text line is produced by the production envelope helper
:func:`.._common._action_text_lines` from the very notices the JSON envelope
carries, so these tests drive that helper rather than reimplementing argv
rendering; a second renderer here would defeat what they exist to prove.
"""

from __future__ import annotations

from datetime import date

import pytest

from ....application.overview.calendar import build_overview_calendar
from ....application.overview.calendar_models import OverviewCalendarRange, OverviewStatusReport
from ....application.overview.coverage import AdvisedObligation, CoverageAdviceReason, ObligationCoverageReport
from ....application.overview.next_actions import OverviewStatusNextStepId
from ....core.json_contract import Notice, ResolvedNoticeAction
from ....domain.deadlines.models import EntityType, IrpfEstimationRegime, IrpfIncomeCategory, IVARegime, TaxpayerProfile
from .._common import _action_text_lines
from .._overview_rendering import (
    overview_calendar_output,
    overview_coverage_notices,
    overview_status_output,
)

pytestmark = [pytest.mark.integration, pytest.mark.hex_entrypoint]


@pytest.fixture(autouse=True)
def _english_operator_wording():
    """Render this module's assertions in English.

    Every test here asserts the ENGLISH operator wording -- "3 modelo ... in
    progress", "discarded", "No saved declaration drafts" -- while the configured
    output language defaults to Spanish. Without the pin the line searches match
    nothing and the ``next(...)`` lookups raise StopIteration rather than
    reporting a wording problem, which is a confusing way to learn the language
    was wrong. The subject of these tests is the WORDING, so the language is
    pinned once for the module.
    """
    from ....core.config import override_settings

    with override_settings(cadrumo_output_language="en"):
        yield


def _report(
    *,
    transactions: int = 0,
    invoices: int = 0,
    drafts: int = 0,
    work_units: int = 0,
    discarded_work_units: int = 0,
    unreadable_rows: int = 0,
    active_profile_name: str | None = "Test Persona",
    unsupported_work_create_modelos: tuple[str, ...] = (),
) -> OverviewStatusReport:
    return OverviewStatusReport(
        active_profile_name=active_profile_name,
        transactions=transactions,
        invoices=invoices,
        drafts=drafts,
        work_units=work_units,
        discarded_work_units=discarded_work_units,
        calculation_revisions=0,
        unreadable_rows=unreadable_rows,
        unsupported_work_create_modelos=unsupported_work_create_modelos,
    )


def _steps(notices: list[Notice]) -> dict[str, Notice]:
    """Index the guidance notices by the closed step id they declare."""
    return {(notice.context or {})["step"]: notice for notice in notices}


def _action(notice: Notice) -> ResolvedNoticeAction:
    action = notice.action
    assert isinstance(action, ResolvedNoticeAction), f"{notice.code} carries no resolved notice action"
    return action


_EVERY_REAL_WORKSPACE_STATE = (
    _report(),
    _report(active_profile_name=None),
    _report(transactions=1),
    _report(invoices=1),
    _report(transactions=1, work_units=1),
    _report(transactions=1, unsupported_work_create_modelos=("210",)),
    _report(transactions=1, work_units=1, unsupported_work_create_modelos=("210",)),
    _report(transactions=1, unreadable_rows=4),
)


@pytest.mark.parametrize("report", _EVERY_REAL_WORKSPACE_STATE)
def test_status_text_and_envelope_notices_share_one_action_projection(report: OverviewStatusReport) -> None:
    """Text and JSON render forward guidance from the same resolved objects.

    This is the whole point of the migration: the executable lines the text
    surface shows are generated by the production envelope helper FROM the
    notices the JSON envelope carries. If a second projection were reintroduced
    the two sides could disagree, and this equality would not hold.
    """
    lines, notices = overview_status_output(report)

    executable_lines = _action_text_lines(notices)
    actionable = [notice for notice in notices if isinstance(notice.action, ResolvedNoticeAction)]
    assert len(executable_lines) == len(actionable)

    # Each executable line is derived from its own notice and from nothing else.
    for line, notice in zip(executable_lines, actionable, strict=True):
        assert line.startswith("next_action\t")
        for token in _action(notice).action.cli_path or ():
            assert token in line

    # The text body states the explanations, never a command.
    for notice in notices:
        assert notice.message in "\n".join(lines)


@pytest.mark.parametrize("report", _EVERY_REAL_WORKSPACE_STATE)
def test_no_status_line_or_notice_message_carries_command_prose(report: OverviewStatusReport) -> None:
    """Executable identity lives on the action, never in prose.

    The body lines and the notice messages are localized explanations. Only the
    action-derived lines, which the shared envelope appends, may name a command.
    """
    lines, notices = overview_status_output(report)

    for line in lines:
        assert "aeat " not in line
        assert "aeat`" not in line
    for notice in notices:
        assert "aeat " not in notice.message


@pytest.mark.parametrize("report", _EVERY_REAL_WORKSPACE_STATE)
def test_every_declared_status_action_resolves_against_the_live_command_surface(
    report: OverviewStatusReport,
) -> None:
    """A guidance action always carries a real live CLI path and catalogue id."""
    _, notices = overview_status_output(report)

    for notice in notices:
        if not isinstance(notice.action, ResolvedNoticeAction):
            continue
        resolved = _action(notice)
        assert resolved.action.action_id.startswith("operator.")
        assert resolved.action.cli_path
        assert all(not token.startswith("-") for token in resolved.action.cli_path)


def test_empty_workspace_asks_for_an_import_without_pretending_it_is_executable() -> None:
    """A cold workspace is told to import, and told nothing it cannot run.

    ``ledger import`` needs a statement file and a provider the status surface
    cannot know, so the row is guidance only. Emitting a placeholder command
    here is exactly the dishonesty this projection removes.
    """
    _, notices = overview_status_output(_report())
    steps = _steps(notices)

    assert OverviewStatusNextStepId.IMPORT_TRANSACTIONS.value in steps
    assert steps[OverviewStatusNextStepId.IMPORT_TRANSACTIONS.value].action is None
    assert _action(steps[OverviewStatusNextStepId.REVIEW_LEDGER.value]).action.target_command_key == "ledger.review"


def test_missing_active_profile_leads_with_a_real_profile_creation_action() -> None:
    """The first thing a profileless workspace is handed is an executable step."""
    _, notices = overview_status_output(_report(active_profile_name=None))

    first = notices[0]
    assert (first.context or {})["step"] == OverviewStatusNextStepId.CREATE_PROFILE.value
    assert _action(first).action.target_command_key == "config.profile.create"


def test_unreadable_rows_raise_an_executable_storage_diagnostics_step() -> None:
    """The storage line states the finding; the guidance row carries the remedy."""
    lines, notices = overview_status_output(_report(transactions=6, unreadable_rows=4))
    steps = _steps(notices)

    assert any("4" in line for line in lines)
    assert _action(steps[OverviewStatusNextStepId.REPAIR_STORAGE.value]).action.target_command_key == "config.repair"


def test_next_step_not_import_once_ledger_has_transactions() -> None:
    """M19: after ledger entries exist, the guidance must not say "import".

    It points at the real next action instead.
    """
    _, notices = overview_status_output(_report(transactions=6))
    steps = _steps(notices)

    assert OverviewStatusNextStepId.IMPORT_TRANSACTIONS.value not in steps
    assert _action(steps[OverviewStatusNextStepId.REVIEW_LEDGER.value]).action.target_command_key == "ledger.review"
    assert OverviewStatusNextStepId.START_WORK_UNIT_FROM_LEDGER.value in steps


def test_next_step_does_not_suggest_unsupported_m210_work_create() -> None:
    """IRNR profiles must not be steered toward unsupported Modelo 210 work units."""
    _, notices = overview_status_output(
        _report(transactions=6, unsupported_work_create_modelos=("210",)),
    )
    steps = _steps(notices)

    assert OverviewStatusNextStepId.IMPORT_TRANSACTIONS.value not in steps
    assert OverviewStatusNextStepId.START_WORK_UNIT_FROM_LEDGER.value not in steps
    diverted = _action(steps[OverviewStatusNextStepId.MODELO_210_SEDE_ONLY.value])
    assert diverted.action.target_command_key == "modelo.describe"
    assert [(binding.argument_name, binding.value) for binding in diverted.argument_bindings] == [("modelo", "210")]
    assert "G320" in steps[OverviewStatusNextStepId.MODELO_210_SEDE_ONLY.value].message


def test_next_step_resumes_modelo_work_when_work_units_exist() -> None:
    """An operator with in-progress work units is pointed at resuming that work."""
    _, notices = overview_status_output(_report(transactions=6, work_units=2))
    steps = _steps(notices)

    assert OverviewStatusNextStepId.IMPORT_TRANSACTIONS.value not in steps
    assert (
        _action(steps[OverviewStatusNextStepId.RESUME_WORK_UNIT.value]).action.target_command_key == "modelo.work.list"
    )


