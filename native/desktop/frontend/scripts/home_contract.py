"""Produce the desktop's Home wire types from the JSON schema of the registered Python models.

``src/shell/homeContract.ts`` holds the request of the ``workbench.generation`` read the window
asks for and the one state of its result the desktop host passes on, the ``home`` state, as the
production operation registry binds their public schemas, written with
``dev.fixture_projections.typescript_wire_types``: field names, nullity and closed vocabularies as
the application serialises them. The window receives no other state of the generation, so no other
state's type is written.

``scripts/home-contract.mjs`` drives this module and formats what it writes; run that, not this.
This module writes one JSON object to standard output: the repository's TypeScript module bound as
``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, cast

from dev.fixture_projections.typescript_wire_types import (
    TypeScriptWriter,
    literal,
    models_in,
    omittable_fields,
    reach,
    ts_name,
)
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from cadrumo.entrypoints.operation_composition import build_production_operation_registry

_HEADER = """\
// Generated by scripts/home_contract.py from the JSON schema of the
// registered Python models; do not edit. Regenerate with
// `node scripts/home-contract.mjs`; `--check` fails when it is stale.
"""

#: The definition whose generation carries the Home state the window reads.
HOME_DEFINITION = "workbench.generation"

#: The field of the generation the desktop host passes on, and the only one.
HOME_STATE = "home"


def _field_model(model: type[BaseModel], field: str) -> type[BaseModel]:
    """The one model a field of ``model`` holds, found through the registered models and not by name."""
    found = list(models_in(model.model_fields[field].annotation))
    if len(found) != 1:
        raise SystemExit(f"{model.__name__}.{field} holds no single model")
    return found[0]


def _models() -> tuple[type[BaseModel], type[BaseModel]]:
    """The registered request, and the Home state of the registered result's generation."""
    registry = build_production_operation_registry()
    contract = registry.lookup_public_contract(HOME_DEFINITION)
    if contract.result_schema is None:
        raise SystemExit(f"{HOME_DEFINITION} registers no public result")
    request = registry.lookup_public_schema_binding(contract.request_schema).model_type
    result = registry.lookup_public_schema_binding(contract.result_schema).model_type
    generation = _field_model(result, "generation")
    return request, _field_model(generation, HOME_STATE)


def render() -> str:
    """The generated Home contract module, before the frontend's formatter writes it."""
    request, home = _models()
    models = [(home, "serialization"), (request, "validation")]
    _, schema = models_json_schema(cast(Any, models), ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    received = reach(defs, [home.__name__])
    writer = TypeScriptWriter(
        defs,
        sent_only=reach(defs, [request.__name__]) - received,
        omittable=omittable_fields([request, home], defs),
    )
    names = sorted((name for name in defs if not writer.inlined(name)), key=ts_name)
    blocks = [writer.definition(name) for name in names]
    blocks.append(
        f"/** The registered request of {literal(HOME_DEFINITION)}; the host fills the profile. */\n"
        f"export type HomeRequest = {ts_name(request.__name__)};\n\n"
        f"/** What the desktop host passes on of that read's result: its {literal(HOME_STATE)} state\n"
        " * under the product's own names, and nothing else of the generation. */\n"
        f"export type HomeServed = {ts_name(home.__name__)};"
    )
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
