"""Produce the desktop's profile wire types from the JSON schema of the registered Python models.

``src/shell/profileContract.ts`` holds the request and result of every profile definition the
window reads, as the production operation registry binds their public schemas, written with
``dev.fixture_projections.typescript_wire_types``: field names, nullity and closed vocabularies
as the application serialises them. A result field is always present unless the model leaves it
out while absent or empty; a field of what the window sends may be left out where the model gives
it a default.

``scripts/profile-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module
bound as ``bound``, which the driver refuses a longer formatted module by, and the unformatted
source as ``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, cast

from dev.fixture_projections.typescript_wire_types import (
    TypeScriptWriter,
    literal,
    omittable_fields,
    reach,
    ts_name,
)
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from cadrumo.entrypoints.operation_composition import build_production_operation_registry

_HEADER = """\
// Generated by scripts/profile_contract.py from the JSON schema of the
// registered Python models; do not edit. Regenerate with
// `node scripts/profile-contract.mjs`; `--check` fails when it is stale.
"""

#: The profile definitions whose request and result the window reads, by definition id.
PROFILE_DEFINITIONS: tuple[str, ...] = ("user-profile.record-groups",)


def _model_roots() -> list[tuple[str, str, type[BaseModel]]]:
    """Each definition's registered request and public result model, as ``(definition, role, model)``."""
    registry = build_production_operation_registry()
    roots: list[tuple[str, str, type[BaseModel]]] = []
    for definition_id in PROFILE_DEFINITIONS:
        contract = registry.lookup_public_contract(definition_id)
        roots.append(
            (definition_id, "request", registry.lookup_public_schema_binding(contract.request_schema).model_type)
        )
        if contract.result_schema is None:
            raise SystemExit(f"{definition_id} registers no public result")
        roots.append(
            (definition_id, "result", registry.lookup_public_schema_binding(contract.result_schema).model_type)
        )
    return roots


def render() -> str:
    """The generated profile contract module, before the frontend's formatter writes it."""
    roots = _model_roots()
    sent = [model for _, role, model in roots if role == "request"]
    models = [(model, "serialization") for _, _, model in roots] + [(model, "validation") for model in sent]
    _, schema = models_json_schema(cast(Any, list(dict.fromkeys(models))), ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    received = reach(defs, (model.__name__ for _, role, model in roots if role != "request"))
    writer = TypeScriptWriter(
        defs,
        sent_only=reach(defs, (model.__name__ for model in sent)) - received,
        omittable=omittable_fields([model for _, _, model in roots], defs),
    )
    names = sorted((name for name in defs if not writer.inlined(name)), key=ts_name)
    blocks = [writer.definition(name) for name in names]
    by_definition: dict[str, list[tuple[str, str]]] = {}
    for definition_id, role, model in roots:
        by_definition.setdefault(definition_id, []).append((role, model.__name__))
    blocks.append(
        "/** Each profile definition's registered request and result, as the runtime's\n"
        " * contract names them; a request names the profile the host fills. */\n"
        "export type ProfileContracts = {\n"
        + "\n".join(
            f"  {literal(definition_id)}: {{ "
            + " ".join(f"{role}: {ts_name(model_name)};" for role, model_name in parts)
            + " };"
            for definition_id, parts in sorted(by_definition.items())
        )
        + "\n};"
    )
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
