"""Produce the desktop's Reference wire types from the JSON schema of the registered Python models.

``src/shell/referenceContract.ts`` holds the request and the result of the ``reference.corpus.search``
read the window asks for, as the production operation registry binds their public schemas, written
with ``dev.fixture_projections.typescript_wire_types``: field names, nullity and closed vocabularies
as the application serialises them. The desktop host passes the result on as it is served.

``scripts/reference-contract.mjs`` drives this module and formats what it writes; run that, not this.
This module writes one JSON object to standard output: the repository's TypeScript module bound as
``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, cast

from dev.fixture_projections.typescript_wire_types import (
    TypeScriptWriter,
    literal,
    omittable_fields,
    reach,
    ts_name,
)
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from cadrumo.entrypoints.operation_composition import build_production_operation_registry

_HEADER = """\
// Generated by scripts/reference_contract.py from the JSON schema of the
// registered Python models; do not edit. Regenerate with
// `node scripts/reference-contract.mjs`; `--check` fails when it is stale.
"""

#: The definition that searches the corpus bundled with the product.
REFERENCE_DEFINITION = "reference.corpus.search"


def _models() -> tuple[type[BaseModel], type[BaseModel]]:
    """The registered request and result models of the corpus search."""
    registry = build_production_operation_registry()
    contract = registry.lookup_public_contract(REFERENCE_DEFINITION)
    if contract.result_schema is None:
        raise SystemExit(f"{REFERENCE_DEFINITION} registers no public result")
    request = registry.lookup_public_schema_binding(contract.request_schema).model_type
    result = registry.lookup_public_schema_binding(contract.result_schema).model_type
    return request, result


def render() -> str:
    """The generated Reference contract module, before the frontend's formatter writes it."""
    request, result = _models()
    models = [(result, "serialization"), (request, "validation")]
    _, schema = models_json_schema(cast(Any, models), ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    received = reach(defs, [result.__name__])
    writer = TypeScriptWriter(
        defs,
        sent_only=reach(defs, [request.__name__]) - received,
        omittable=omittable_fields([request, result], defs),
    )
    names = sorted((name for name in defs if not writer.inlined(name)), key=ts_name)
    blocks = [writer.definition(name) for name in names]
    blocks.append(
        f"/** The registered request of {literal(REFERENCE_DEFINITION)}; the host fills the profile. */\n"
        f"export type ReferenceRequest = {ts_name(request.__name__)};\n\n"
        "/** What the desktop host passes on of that read's result, under the product's own names. */\n"
        f"export type ReferenceServed = {ts_name(result.__name__)};"
    )
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
