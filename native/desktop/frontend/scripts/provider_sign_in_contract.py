"""Produce the desktop's closed provider sign-in word lists from the agent service's declarations.

``src/shell/providerSignInContract.ts`` holds the closed words a provider sign-in or status read
serves: the helper's and the service's causes, the command-line app state causes, the next steps
and the provider-settings refusal codes, each read from the Python declaration that closes it, in
declaration order. Refusal codes the service emits inline (``busy``, ``unsupported_flow``,
``invalid_request``, ``service_failed``) have no closed Python declaration and are not listed.

``scripts/provider-sign-in-contract.mjs`` drives this module and formats what it writes; run that,
not this. This module writes one JSON object to standard output: the repository's TypeScript module
bound as ``bound`` and the unformatted source as ``module``.
"""

from __future__ import annotations

import json
import sys
from enum import StrEnum
from typing import get_args

from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES

from cadrumo_agent_service.providers.application.contracts import (
    CliStateCause,
    HelperCause,
    NextStep,
    ProviderSettingsRefusalCode,
    ServiceCause,
)

_HEADER = """\
// Generated by scripts/provider_sign_in_contract.py from the agent service's
// closed declarations; do not edit. Regenerate with
// `node scripts/provider-sign-in-contract.mjs`; `--check` fails when it is stale.
"""


def _words(declared: object) -> list[str]:
    """The values of a Literal alias or StrEnum, in declaration order."""
    if isinstance(declared, type) and issubclass(declared, StrEnum):
        return [member.value for member in declared]
    return list(get_args(declared))


def _block(const: str, type_name: str, doc: str, words: list[str]) -> str:
    items = "".join(f'  "{word}",\n' for word in words)
    return (
        f"/** {doc} */\nexport const {const} = [\n{items}] as const;\n"
        f"export type {type_name} = (typeof {const})[number];"
    )


def render() -> str:
    """The generated module, before the frontend's formatter writes it."""
    sign_in = list(dict.fromkeys([*_words(HelperCause), *_words(ServiceCause)]))
    blocks = [
        _block(
            "SIGN_IN_CAUSES",
            "SignInCause",
            "Why a sign-in attempt did not succeed: the helper's and the service's words.",
            sign_in,
        ),
        _block(
            "CLI_STATE_CAUSES",
            "CliStateCause",
            "Why a command-line app's state is not established.",
            _words(CliStateCause),
        ),
        _block("NEXT_STEPS", "NextStep", "What a person can do about a cause.", _words(NextStep)),
        _block(
            "PROVIDER_SETTINGS_REFUSAL_CODES",
            "ProviderSettingsRefusalCode",
            "The closed refusal codes of a provider-settings read or change.",
            _words(ProviderSettingsRefusalCode),
        ),
    ]
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
