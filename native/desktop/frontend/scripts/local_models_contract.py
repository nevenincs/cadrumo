"""Produce the desktop's local model list and local engine wire types from the agent service's models.

``src/shell/localModelsContract.ts`` holds the answers the agent service gives its ``local_models`` and
``local_engine`` reads and the changes to them (``local_model_add``, ``local_model_remove``,
``local_models_reset``, ``reading_model_choose``, ``task_model_choose`` and ``local_engine_choose``), written with
``dev.fixture_projections.typescript_wire_types`` from the JSON schema of
``LocalModelListStatus`` and ``LocalEngineStatus`` in serialization mode: the service answers each with
``model_dump(mode="json")``, without aliases or exclusions, and the desktop host passes that document on
to the window as it is. A refusal crosses as the host's own refusal code and is not typed here.

``scripts/local-models-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound
as ``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, cast

from dev.fixture_projections.typescript_wire_types import TypeScriptWriter, omittable_fields, reach, ts_name
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from cadrumo_agent_service.providers.application.contracts import LocalEngineStatus, LocalModelListStatus

_HEADER = """\
// Generated by scripts/local_models_contract.py from the JSON schema of the
// agent service's local model list and local engine answers, which the host
// passes on unchanged; do not edit. Regenerate with
// `node scripts/local-models-contract.mjs`; `--check` fails when it is stale.
"""

#: The answers the service serves the reads and the changes to them, each the model it dumps.
ANSWERS: tuple[type[BaseModel], ...] = (LocalModelListStatus, LocalEngineStatus)


def render() -> str:
    """The generated local models contract module, before the frontend's formatter writes it."""
    models = [(model, "serialization") for model in ANSWERS]
    _, schema = models_json_schema(cast(Any, models), ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    reached = reach(defs, (model.__name__ for model in ANSWERS))
    writer = TypeScriptWriter(defs, sent_only=set(), omittable=omittable_fields(ANSWERS, defs))
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    return _HEADER + "\n" + "\n\n".join(writer.definition(name) for name in names) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
