"""Produce the desktop's ledger enums and field masks from the Python models that own them.

``src/shell/ledgerContract.ts`` holds the closed vocabularies the product fixes in its own
language, not the ones the registry dates: a movement's classification, direction and
lifecycle, an invoice's payment status and Modelo 349 operation key, the kinds of import
diagnostic, and the fields each correction may name. Each is read from the enum or request
model that owns it, so the window holds no list of its own and a member added there reaches
it on regeneration.

It also holds what a stored code alone decides and every drawn row needs at once, such as
whether a lifecycle takes a change or which fields a direction locks: each is worked out here
by calling the function or reading the constant that owns the rule, over all the codes. The
same goes for a static route: which facts make a movement's identity, which field a readiness
reason is put right in, which correction waits on a verdict.

``scripts/ledger-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module
bound as ``bound``, which the driver refuses a longer formatted module by, and the unformatted
source as ``module``.
"""

