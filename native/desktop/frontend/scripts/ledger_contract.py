"""Produce the desktop's ledger enums and field masks from the Python models that own them.

``src/shell/ledgerContract.ts`` holds the closed vocabularies the product fixes in its own
language, not the ones the registry dates: a movement's classification, direction and
lifecycle, an invoice's payment status and Modelo 349 operation key, the kinds of import
diagnostic, and the fields each correction may name. Each is read from the enum or request
model that owns it, so the window holds no list of its own and a member added there reaches
it on regeneration.

``scripts/ledger-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes the unformatted source to standard output.
"""

from __future__ import annotations

import sys
from collections.abc import Sequence
from enum import StrEnum

from pydantic import BaseModel

from cadrumo.application.invoices.catalogue_lifecycle import CatalogueInvoicePatch
from cadrumo.application.ledger.evidence_mutation_operation import LedgerEvidenceUpdatePatch
from cadrumo.application.ledger.update_contracts import LedgerUpdatePatch
from cadrumo.application.transactions.diagnostics import LedgerImportDiagnosticKind
from cadrumo.core.aggregation import IntracomOperationType
from cadrumo.domain.invoices.enums import PaymentStatus
from cadrumo.domain.transactions.enums import BusinessClassification, TransactionDirection, TransactionLifecycleState

_HEADER = """\
// Generated by scripts/ledger_contract.py from the ledger's Python enums and
// correction models; do not edit. Regenerate with
// `node scripts/ledger-contract.mjs`; `--check` fails when it is stale.
"""

#: Each enum as ``(constant, type, guard, doc, enum)``; a guard of ``None`` writes none.
_ENUMS: tuple[tuple[str, str, str | None, str, type[StrEnum]], ...] = (
    (
        "CLASSIFICATIONS",
        "Classification",
        "isClassification",
        "A movement's classifications: the three a person decides, then the dispositions the product sets.",
        BusinessClassification,
    ),
    ("DIRECTIONS", "Direction", "isDirection", "Which way a movement's money went.", TransactionDirection),
    (
        "LIFECYCLE_STATES",
        "LifecycleState",
        "isLifecycleState",
        "Where a movement stands in its life.",
        TransactionLifecycleState,
    ),
    ("PAYMENT_STATUSES", "PaymentStatus", "isPaymentStatus", "Where an invoice stands in its payment.", PaymentStatus),
    (
        "OPERATION_TYPES",
        "OperationType",
        None,
        "The Modelo 349 operation keys an invoice may carry.",
        IntracomOperationType,
    ),
    (
        "IMPORT_ISSUES",
        "ImportIssue",
        None,
        "What an import marked on a movement, as the list filters it.",
        LedgerImportDiagnosticKind,
    ),
)

#: Each mask as ``(constant, type, doc, model)``.
_MASKS: tuple[tuple[str, str, str, type[BaseModel]], ...] = (
    (
        "LEDGER_UPDATE_FIELDS",
        "LedgerUpdateField",
        "The fields a movement may be corrected in.",
        LedgerUpdatePatch,
    ),
    (
        "INVOICE_UPDATE_FIELDS",
        "InvoiceUpdateField",
        "The fields a stored invoice may be corrected in; its identity and lines are not among them.",
        CatalogueInvoicePatch,
    ),
    (
        "EVIDENCE_UPDATE_FIELDS",
        "EvidenceUpdateField",
        "The fields an evidence record may be corrected in.",
        LedgerEvidenceUpdatePatch,
    ),
)


def _literal(values: Sequence[str]) -> str:
    return "[\n" + "".join(f'  "{value}",\n' for value in values) + "] as const;"


def _names(constant: str, type_name: str, doc: str, values: Sequence[str], guard: str | None) -> str:
    lines = [
        f"/** {doc} */",
        f"export const {constant} = {_literal(values)}",
        f"export type {type_name} = (typeof {constant})[number];",
    ]
    if guard is not None:
        lines += [
            f"export const {guard} = (id: string): id is {type_name} =>",
            f"  ({constant} as readonly string[]).includes(id);",
        ]
    return "\n".join(lines)


def render() -> str:
    """The generated ledger contract module, before the frontend's formatter writes it."""
    blocks = [
        _names(constant, type_name, doc, [member.value for member in enum], guard)
        for constant, type_name, guard, doc, enum in _ENUMS
    ]
    blocks += [
        _names(constant, type_name, doc, list(model.model_fields), None) for constant, type_name, doc, model in _MASKS
    ]
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the unformatted module to standard output."""
    sys.stdout.write(render())


if __name__ == "__main__":
    main()
