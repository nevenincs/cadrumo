"""Produce the desktop's agent gateway wire types from the agent's pinned published schema.

``src/shell/agentGatewayContract.ts`` holds every definition of the answers the host relays from the
agent unchanged: a model's licence (``ModelLicenceResponse``), the skill inventory
(``SkillListResponse``), one skill (``SkillDetailRecord``) and its checks (``SkillVerificationRecord``),
the attachment policy (``AttachmentPolicyResponse``), a failed run's ``ProviderCondition``, and the
vocabularies of a run the host passes on as the agent serves them: a run's ``ThreadStatus``, a tool
call's ``ToolCallStatus`` and ``ToolKind``, and a pending clarification's ``ClarificationQuestion``, as
``cadrumo_agent_service.providers.application.served_catalog.agent_definitions`` states the agent's pinned
schema. The service changes nothing on these routes. The agent's schema names a
field required only where it has no default, so every other field may be absent from the wire and is
optional here.

``scripts/agent-gateway-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound
as ``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Final

from dev.fixture_projections.typescript_wire_types import TypeScriptWriter, reach, ts_name
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES

from cadrumo_agent_service.providers.application.served_catalog import agent_definitions

RELAYED_ANSWERS: Final = (
    "AttachmentPolicyResponse",
    "ClarificationQuestion",
    "ModelLicenceResponse",
    "ProviderCondition",
    "SkillDetailRecord",
    "SkillListResponse",
    "SkillVerificationRecord",
    "ThreadStatus",
    "ToolCallStatus",
    "ToolKind",
)
"""The agent definitions the host relays unchanged: the attachment policy's, the licence route's, the
skill list's, one skill's and its checks' answers, a failed run's provider condition, a run's status, a
tool call's status and kind, and a pending clarification's questions, which the host passes through as
the agent states them."""

_HEADER = """\
// Generated by scripts/agent_gateway_contract.py from the agent's pinned
// published schema, which the host relays unchanged; do not edit.
// Regenerate with `node scripts/agent-gateway-contract.mjs`; `--check` fails
// when it is stale.
"""


def render() -> str:
    """The generated gateway contract module, before the frontend's formatter writes it."""
    defs = agent_definitions()
    reached = reach(defs, RELAYED_ANSWERS)
    writer = TypeScriptWriter(defs, sent_only=reached, omittable={})
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    return _HEADER + "\n" + "\n\n".join(writer.definition(name) for name in names) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
