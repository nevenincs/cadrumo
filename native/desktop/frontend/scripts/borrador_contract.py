"""Produce the desktop's Borrador 100 wire types from the JSON schema of the registered Python models.

``src/shell/borradorContract.ts`` holds the public result of every Borrador 100 read the window
shows, as the production operation registry binds their public schemas, written with
``dev.fixture_projections.typescript_wire_types``: field names, nullity and closed vocabularies as
the application serialises them. A field is always present unless the model leaves it out while
absent or empty. The desktop host builds each request from the window's selector itself and passes
the settled result on unchanged, so only the results are written.

``scripts/borrador-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module
bound as ``bound``, which the driver refuses a longer formatted module by, and the unformatted
source as ``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, cast

from dev.fixture_projections.typescript_wire_types import (
    TypeScriptWriter,
    literal,
    omittable_fields,
    reach,
    ts_name,
)
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.json_schema import models_json_schema

from cadrumo.entrypoints.operation_composition import build_production_operation_registry

_HEADER = """\
// Generated by scripts/borrador_contract.py from the JSON schema of the
// registered Python models; do not edit. Regenerate with
// `node scripts/borrador-contract.mjs`; `--check` fails when it is stale.
"""

#: The Borrador 100 definitions whose result the window reads, by definition id.
BORRADOR_DEFINITIONS: tuple[str, ...] = (
    "live.borrador.100.compare",
    "live.borrador.100.query",
    "live.borrador.100.read",
)


def _results() -> list[tuple[str, type[BaseModel]]]:
    """Each definition's registered public result model, as ``(definition, model)``."""
    registry = build_production_operation_registry()
    results: list[tuple[str, type[BaseModel]]] = []
    for definition_id in BORRADOR_DEFINITIONS:
        contract = registry.lookup_public_contract(definition_id)
        if contract.result_schema is None:
            raise SystemExit(f"{definition_id} registers no public result")
        results.append((definition_id, registry.lookup_public_schema_binding(contract.result_schema).model_type))
    return results


def render() -> str:
    """The generated Borrador 100 contract module, before the frontend's formatter writes it."""
    results = _results()
    models = [(model, "serialization") for _, model in results]
    _, schema = models_json_schema(cast(Any, list(dict.fromkeys(models))), ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    reached = reach(defs, (model.__name__ for _, model in results))
    writer = TypeScriptWriter(
        defs,
        sent_only=set(),
        omittable=omittable_fields([model for _, model in results], defs),
    )
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    blocks = [writer.definition(name) for name in names]
    blocks.append(
        "/** Each Borrador 100 definition's registered result, as the runtime's contract\n"
        " * names it; the host passes it on unchanged. */\n"
        "export type BorradorContracts = {\n"
        + "\n".join(
            f"  {literal(definition_id)}: {{ result: {ts_name(model.__name__)} }};"
            for definition_id, model in sorted(results)
        )
        + "\n};"
    )
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
