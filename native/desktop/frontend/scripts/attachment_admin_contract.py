"""Produce the desktop's attachment administration wire types from the agent service's answer models.

``src/shell/attachmentAdminContract.ts`` holds the answers the agent service gives its
``attachment_card``, ``attachment_release``, ``attachment_grants`` and ``attachment_grant_revoke``
actions, and ``ReleaseScope``, the reach of the person's approval a release request names. They are
written with ``dev.fixture_projections.typescript_wire_types`` from the JSON schema of each action's
answer union in serialization mode: the service answers each with ``model_dump(mode="json")``, without
aliases or exclusions, and the desktop host passes that document on to the window as it is, refusals
included.

``scripts/attachment-admin-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound
as ``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from typing import Any, Literal

from dev.fixture_projections.typescript_wire_types import TypeScriptWriter, models_in, omittable_fields, reach, ts_name
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import TypeAdapter

from cadrumo_agent_service.providers.application.attachment_releases import (
    AttachmentCardAnswer,
    AttachmentGrantRevokeAnswer,
    AttachmentGrantsAnswer,
    AttachmentReleaseAnswer,
    ReleaseScope,
)

_HEADER = """\
// Generated by scripts/attachment_admin_contract.py from the JSON schema of the
// agent service's attachment administration answers, which the host passes on
// unchanged; do not edit. Regenerate with
// `node scripts/attachment-admin-contract.mjs`; `--check` fails when it is stale.
"""

#: Each root the window names: the answer of each action it asks, and the scope a release names.
ROOTS: tuple[tuple[str, Any], ...] = (
    ("AttachmentCardAnswer", AttachmentCardAnswer),
    ("AttachmentReleaseAnswer", AttachmentReleaseAnswer),
    ("AttachmentGrantsAnswer", AttachmentGrantsAnswer),
    ("AttachmentGrantRevokeAnswer", AttachmentGrantRevokeAnswer),
    ("ReleaseScope", ReleaseScope),
)


def render() -> str:
    """The generated attachment administration contract module, before the frontend's formatter writes it."""
    mode: Literal["serialization"] = "serialization"
    inputs = [(name, mode, TypeAdapter[Any](root)) for name, root in ROOTS]
    _, schema = TypeAdapter.json_schemas(inputs, ref_template="#/$defs/{model}")
    defs: dict[str, Any] = schema["$defs"]
    missing = [name for name, _ in ROOTS if name not in defs]
    if missing:
        raise SystemExit(f"the schema does not define the roots {missing}")
    reached = reach(defs, (name for name, _ in ROOTS))
    models = [model for _, root in ROOTS for model in models_in(root)]
    writer = TypeScriptWriter(defs, sent_only=set(), omittable=omittable_fields(models, defs))
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    return _HEADER + "\n" + "\n\n".join(writer.definition(name) for name in names) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
