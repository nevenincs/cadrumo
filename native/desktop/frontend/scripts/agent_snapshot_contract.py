"""Produce the desktop's conversation answer wire types from the JSON schema of the host's own types.

``src/shell/agentSnapshotContract.ts`` holds what the desktop host answers its ``agent_snapshot``,
``agent_history`` and ``agent_pending`` commands with: the records it composes from a conversation's runs
and the questionnaires and approvals its newest reply waits on. The host writes these itself, so their
schema is the host's: ``src-tauri/src/agent/snapshot.schema.json``, which a host unit test keeps equal to
the serde types that serialize them. A field the host copies from a gateway answer names the agent's own
definition there; each such name is imported from the generated module that defines it, after checking
that the agent's pinned schema defines it. Every field the host's schema requires is always written; one
it does not require may be left out of the wire.

``scripts/agent-snapshot-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound
as ``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys
from collections.abc import Callable, Mapping
from pathlib import Path
from typing import Any, Final, cast

from dev.fixture_projections.typescript_wire_types import TypeScriptWriter, reach, refs, ts_name
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES

from cadrumo_agent_service.providers.application.served_catalog import agent_definitions, served_schema

SCHEMA: Final = Path(__file__).resolve().parents[2] / "src-tauri" / "src" / "agent" / "snapshot.schema.json"
"""The host's schema of its conversation answers, as its unit test writes it."""

RELAYED: Final[Mapping[str, tuple[str, Callable[[], Mapping[str, Any]]]]] = {
    "Effort": ("./agentCatalogContract", served_schema),
    "Provider": ("./agentGatewayContract", agent_definitions),
    "ProviderCondition": ("./agentGatewayContract", agent_definitions),
    "ProviderTransport": ("./agentGatewayContract", agent_definitions),
    "ThreadStatus": ("./agentGatewayContract", agent_definitions),
    "ToolCallStatus": ("./agentGatewayContract", agent_definitions),
    "ToolKind": ("./agentGatewayContract", agent_definitions),
    "ToolReach": ("./agentGatewayContract", agent_definitions),
}
"""The agent definitions a host field relays unchanged: the generated module that defines each, and the
schema it is read from there."""

_HEADER = """\
// Generated by scripts/agent_snapshot_contract.py from the JSON schema of the
// conversation answers the desktop host composes; do not edit. Regenerate
// with `node scripts/agent-snapshot-contract.mjs`; `--check` fails when it is
// stale.
"""


def nullable_unions(node: object) -> object:
    """``node`` with each list of types written as a union of single-type schemas, as the writer reads them."""
    if isinstance(node, list):
        return [nullable_unions(item) for item in cast(list[object], node)]
    if not isinstance(node, dict):
        return node
    mapping = {key: nullable_unions(value) for key, value in cast(dict[str, object], node).items()}
    kinds = mapping.get("type")
    if not isinstance(kinds, list):
        return mapping
    rest = {key: value for key, value in mapping.items() if key != "type"}
    members = [({"type": kind} if kind == "null" else {**rest, "type": kind}) for kind in cast(list[str], kinds)]
    return {key: value for key, value in rest.items() if key in ("description", "title")} | {"anyOf": members}


def host_definitions() -> tuple[str, dict[str, Any]]:
    """The schema's root and its definitions, each list of types written as a union."""
    document = json.loads(SCHEMA.read_text(encoding="utf-8"))
    defs = cast(dict[str, Any], nullable_unions(document["$defs"]))
    return document["root"], defs


def relayed_names(defs: Mapping[str, Any]) -> set[str]:
    """The agent definitions the host's types name, each checked against the schema it is read from."""
    named = {name for node in defs.values() for name in refs(node)} - set(defs)
    unknown = sorted(named - set(RELAYED))
    if unknown:
        raise SystemExit(f"the host's schema names definitions it does not define: {unknown}")
    for name in sorted(named):
        _, source = RELAYED[name]
        if name not in source():
            raise SystemExit(f"the agent's pinned schema does not define {name}")
    return named


def render() -> str:
    """The generated conversation answer contract module, before the frontend's formatter writes it."""
    root, defs = host_definitions()
    relayed = relayed_names(defs)
    placed: dict[str, Any] = {**defs, **{name: {} for name in relayed}}
    reached = reach(placed, (root,)) - relayed
    omittable = {
        name: frozenset(node["properties"]) - frozenset(node.get("required", ()))
        for name, node in defs.items()
        if "properties" in node
    }
    writer = TypeScriptWriter(placed, sent_only=set(), omittable=omittable)
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    written: list[str] = []
    imported: dict[str, set[str]] = {}
    for name in names:
        written.append(writer.definition(name))
        for used in writer.named & relayed:
            imported.setdefault(RELAYED[used][0], set()).add(used)
    imports = [
        f"import type {{ {', '.join(sorted(used))} }} from {json.dumps(module)};"
        for module, used in sorted(imported.items())
    ]
    return _HEADER + "\n" + "\n".join(imports) + "\n\n" + "\n\n".join(written) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
