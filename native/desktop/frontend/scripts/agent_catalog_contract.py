"""Produce the desktop's provider catalog wire types from the catalog the agent service relays.

``src/shell/agentCatalogContract.ts`` holds every definition of the catalog answer the service relays,
as ``cadrumo_agent_service.providers.application.served_catalog.served_schema`` states it: the agent's
pinned published schema with only the service's own changes. The agent's schema names a field required
only where it has no default, so every other field may be absent from the wire and is optional here.

``scripts/agent-catalog-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound
as ``bound``, which the driver refuses a longer formatted module by, and the unformatted source as
``module``.
"""

from __future__ import annotations

import json
import sys

from dev.fixture_projections.typescript_wire_types import TypeScriptWriter, reach, ts_name
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES

from cadrumo_agent_service.providers.application.served_catalog import SERVED_CATALOG_ANSWER, served_schema

_HEADER = """\
// Generated by scripts/agent_catalog_contract.py from the agent's pinned
// published schema and the agent service's own changes to it; do not edit.
// Regenerate with `node scripts/agent-catalog-contract.mjs`; `--check` fails
// when it is stale.
"""


def render() -> str:
    """The generated catalog contract module, before the frontend's formatter writes it."""
    defs = served_schema()
    reached = reach(defs, (SERVED_CATALOG_ANSWER,))
    writer = TypeScriptWriter(defs, sent_only=reached, omittable={})
    names = sorted((name for name in reached if not writer.inlined(name)), key=ts_name)
    return _HEADER + "\n" + "\n\n".join(writer.definition(name) for name in names) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
