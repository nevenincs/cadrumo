"""Produce the desktop's provider-settings wire types from the agent service's declarations.

``src/shell/providerSettingsContract.ts`` holds ``ProviderSettingsRecord``, ``ProviderSettingsAnswer``,
``ProviderSignInSnapshot``, ``ProviderSignInMethod`` and ``ProviderSignInEvent``, each derived from the
service's model or closed ``Literal`` field by field in declaration order: a string or constrained
string is ``string``, a ``bool`` is ``boolean``, an ``int`` is ``number``, a ``StrEnum`` or ``Literal``
is the union of its words, ``tuple[X, ...]`` is ``readonly X[]``, ``dict[str, X]`` is
``Record<string, X>``, a nested model is its generated type's name, and a field that is ``X | None`` or
has a default is optional (``?``), with ``| null`` added for ``None``, because the desktop host omits
an absent value. Any other annotation fails loudly.

The models enable no attribute docstrings, so each field's comment is read from the string literal
that follows its annotation in the class body, parsed from the class source with ``ast``.

``scripts/provider-settings-contract.mjs`` drives this module and formats what it writes; run that,
not this. This module writes one JSON object to standard output: the repository's TypeScript module
bound as ``bound`` and the unformatted source as ``module``.
"""

from __future__ import annotations

import ast
import inspect
import json
import sys
import textwrap
import types
from enum import StrEnum
from typing import Literal, Union, get_args, get_origin

from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES
from pydantic import BaseModel
from pydantic.fields import FieldInfo

from cadrumo_agent_service.providers.application.contracts import (
    ProviderCredentialSource,
    ProviderReadiness,
    ProviderSettingsAnswer,
    ProviderSettingsMode,
    ProviderSignInSnapshot,
    ProviderStatusEntry,
    ProviderStatusReason,
    SignInEvent,
    SignInMethod,
)

_HEADER = """\
// Generated by scripts/provider_settings_contract.py from the agent service's
// provider-settings declarations; do not edit. Regenerate with
// `node scripts/provider-settings-contract.mjs`; `--check` fails when it is stale.
"""

_MODELS: dict[type[BaseModel], str] = {
    ProviderStatusEntry: "ProviderSettingsRecord",
    ProviderSettingsAnswer: "ProviderSettingsAnswer",
    ProviderSignInSnapshot: "ProviderSignInSnapshot",
}
"""Each generated model and the TypeScript name the window knows it by."""

_WORDS: tuple[tuple[object, str, str], ...] = (
    (SignInMethod, "ProviderSignInMethod", "The attended sign-in routes a person can select for a provider."),
    (SignInEvent, "ProviderSignInEvent", "A service-owned sign-in attempt's current transient event."),
    (ProviderSettingsMode, "ProviderSettingsMode", "What the profile holds for a provider."),
    (ProviderCredentialSource, "ProviderCredentialSource", "Where the provider's credential comes from."),
    (ProviderReadiness, "ProviderReadiness", "Whether the provider can be used now, and if not, why."),
    (ProviderStatusReason, "ProviderStatusReason", "Why a provider is not usable, as a stable code."),
)
"""Each closed word list emitted as a named type, and referred to by that name where a field uses it."""


def _quote(word: str) -> str:
    return json.dumps(word, ensure_ascii=False)


def _named(annotation: object) -> str | None:
    for declared, name, _ in _WORDS:
        if annotation == declared:
            return name
    return None


def _join(parts: list[str]) -> str:
    return " | ".join(dict.fromkeys(parts))


def _literal_words(annotation: object, field: str) -> list[str]:
    if isinstance(annotation, type) and issubclass(annotation, StrEnum):
        return [_quote(member.value) for member in annotation]
    words = get_args(annotation)
    if not all(isinstance(word, str) for word in words):
        raise TypeError(f"{field}: only string literals are mapped, not {annotation!r}")
    return [_quote(word) for word in words]


def _type(annotation: object, field: str) -> str:
    """The TypeScript type of one annotation, ``None`` members excluded."""
    named = _named(annotation)
    if named is not None:
        return named
    if annotation is str:
        return "string"
    if annotation is bool:
        return "boolean"
    if annotation is int:
        return "number"
    if isinstance(annotation, type) and issubclass(annotation, StrEnum):
        return _join([_quote(member.value) for member in annotation])
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        if annotation not in _MODELS:
            raise TypeError(f"{field}: nested model {annotation.__name__} has no generated type")
        return _MODELS[annotation]
    origin = get_origin(annotation)
    args = get_args(annotation)
    if origin is Literal:
        return _join(_literal_words(annotation, field))
    if origin in (Union, types.UnionType):
        return _join([_type(arg, field) for arg in args if arg is not type(None)])
    if origin is tuple:
        if len(args) != 2 or args[1] is not Ellipsis:
            raise TypeError(f"{field}: only tuple[X, ...] is mapped, not {annotation!r}")
        inner = _type(args[0], field)
        return f"readonly ({inner})[]" if " | " in inner else f"readonly {inner}[]"
    if origin is dict:
        if len(args) != 2 or args[0] is not str:
            raise TypeError(f"{field}: only dict[str, X] is mapped, not {annotation!r}")
        return f"Record<string, {_type(args[1], field)}>"
    raise TypeError(f"{field}: no TypeScript mapping for {annotation!r}")


def _member(name: str, info: FieldInfo) -> tuple[str, str]:
    """The field's optional marker and its TypeScript type."""
    annotation = info.annotation
    nullable = get_origin(annotation) in (Union, types.UnionType) and type(None) in get_args(annotation)
    ts_type = _type(annotation, name) + (" | null" if nullable else "")
    return ("" if info.is_required() and not nullable else "?"), ts_type


def _docstrings(model: type[BaseModel]) -> dict[str, str]:
    """Each field's attribute docstring: the string literal right after its annotation."""
    tree = ast.parse(textwrap.dedent(inspect.getsource(model)))
    body = tree.body[0]
    if not isinstance(body, ast.ClassDef):
        raise TypeError(f"{model.__name__}: source is not a class")
    found: dict[str, str] = {}
    for previous, node in zip(body.body, body.body[1:], strict=False):
        if (
            isinstance(previous, ast.AnnAssign)
            and isinstance(previous.target, ast.Name)
            and isinstance(node, ast.Expr)
            and isinstance(node.value, ast.Constant)
            and isinstance(node.value.value, str)
        ):
            found[previous.target.id] = " ".join(node.value.value.split())
    return found


def _model_block(model: type[BaseModel], name: str) -> str:
    docs = _docstrings(model)
    lines: list[str] = []
    for field, info in model.model_fields.items():
        optional, ts_type = _member(field, info)
        if field in docs:
            lines.append(f"  /** {docs[field]} */")
        lines.append(f"  {field}{optional}: {ts_type};")
    doc = " ".join((model.__doc__ or "").split())
    body = "\n".join(lines)
    return f"/** {doc} */\nexport type {name} = {{\n{body}\n}};"


def render() -> str:
    """The generated module, before the frontend's formatter writes it."""
    blocks = [
        f"/** {doc} */\nexport type {name} = {_join(_literal_words(declared, name))};" for declared, name, doc in _WORDS
    ]
    blocks += [_model_block(model, name) for model, name in _MODELS.items()]
    return _HEADER + "\n" + "\n\n".join(blocks) + "\n"


def main() -> None:
    """Write the module bound and the unformatted module to standard output."""
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "module": render()}, ensure_ascii=False))


if __name__ == "__main__":
    main()
