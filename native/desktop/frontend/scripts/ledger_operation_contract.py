"""Produce the desktop's ledger operation wire types from the JSON schema of the registered Python models.

Each module under ``src/shell`` named in ``FAMILIES`` holds the request and result of every ledger
definition of one family the window reads, as the production operation registry binds their public
schemas, written with ``dev.fixture_projections.operation_contract_module``: field names, nullity and
closed vocabularies as the application serialises them. A result field is always present unless the
model leaves it out while absent or empty; a field of what the window sends may be left out where the
model gives it a default. A path the window holds only as the host's file token is written with that
token's type (``FIELD_TYPES``). A family is added here when its hand-written shapes are retired.

``scripts/ledger-operation-contract.mjs`` drives this module and formats what it writes; run that, not
this. This module writes one JSON object to standard output: the repository's TypeScript module bound as
``bound``, which the driver refuses a longer formatted module by, and each family's unformatted source as
``modules``, by family name.
"""

from __future__ import annotations

import json
import sys

from dev.fixture_projections.operation_contract_module import WindowType, render_contract_module
from dev.quality.typescript_module_size import MAX_PHYSICAL_LINES

from cadrumo.entrypoints.operation_composition import build_production_operation_registry

_HEADER = """\
// Generated by scripts/ledger_operation_contract.py from the JSON schema of the
// registered Python models; do not edit. Regenerate with
// `node scripts/ledger-operation-contract.mjs`; `--check` fails when it is stale.
"""

#: Each family as ``name: (contracts type, ledger definition ids)``; the driver names the module of each.
FAMILIES: dict[str, tuple[str, tuple[str, ...]]] = {
    "classification": (
        "LedgerClassificationContracts",
        (
            "ledger.counterparty",
            "ledger.llm-diagnostics",
            "ledger.ratios.eligible",
            "ledger.ratios.list",
            "ledger.ratios.set",
            "ledger.ratios.unset",
            "ledger.ratios.validate",
            "ledger.rule.add",
            "ledger.rule.apply",
            "ledger.rule.list",
        ),
    ),
    "invoice": (
        "LedgerInvoiceContracts",
        (
            "ledger.attach",
            "ledger.check",
            "ledger.detach",
            "ledger.invoice.add",
            "ledger.invoice.attach_document",
            "ledger.invoice.duplicate",
            "ledger.invoice.import",
            "ledger.invoice.list",
            "ledger.invoice.match",
            "ledger.invoice.preview",
            "ledger.invoice.remove",
            "ledger.invoice.update",
            "ledger.invoice.view",
            "ledger.link",
        ),
    ),
}

_FILE_TOKEN = WindowType("FileToken", "./ledger")

#: Each family's strings the window types with a name of its own, as ``(schema definition, property)``.
FIELD_TYPES: dict[str, dict[tuple[str, str], WindowType]] = {
    "invoice": {
        ("InvoiceDocumentAttachRequest", "source_path"): _FILE_TOKEN,
        ("InvoiceImportRequest", "source_path"): _FILE_TOKEN,
    },
}


def render(family: str) -> str:
    """The generated module of one family, before the frontend's formatter writes it."""
    contracts_name, definitions = FAMILIES[family]
    return render_contract_module(
        build_production_operation_registry(),
        header=_HEADER,
        definitions=definitions,
        contracts_name=contracts_name,
        subject="ledger",
        field_types=FIELD_TYPES.get(family),
    )


def main() -> None:
    """Write the module bound and each family's unformatted module to standard output."""
    modules = {family: render(family) for family in FAMILIES}
    sys.stdout.write(json.dumps({"bound": MAX_PHYSICAL_LINES, "modules": modules}, ensure_ascii=False))


if __name__ == "__main__":
    main()
