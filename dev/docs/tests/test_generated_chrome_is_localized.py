_REPO_ROOT = Path(__file__).resolve().parents[3]
_GENERATORS = (
    "legal_reference.py",
    "glossary_reference.py",
    "casilla_reference.py",
    "cli_reference.py",
    "cli_tree.py",
)

#: Strings that reach output but are not prose: RST and HTML syntax, catalogue
#: field values, and the Spanish instrument designations that ARE the content.
_NOT_PROSE = re.compile(
    r"""^(
        \s* | [-=`.:*_/\\|<>()\[\]{}#]+ | utf-8 | https?://.* | \.\..* | .*<[a-z/].* | [a-z][a-z0-9_.]*
        | Ley | Orden\  | Real\ Decreto | Real\ Decreto\ Legislativo | Real\ Decreto-ley | art\.\  | es | en
    )$""",
    re.VERBOSE,
)


def _display_literals(path: Path) -> list[tuple[int, str]]:
    """String constants in a generator that look like prose shown to a reader.

    Excluded because none of them reach a reader: docstrings, exception
    messages, ``__all__`` entries, and RST comment blocks (the "generated by"
    provenance header, which docutils never renders).

    Two further exclusions are the command surface rather than prose about it.
    A message built inside an exception subclass reaches a developer reading a
    traceback, not a taxpayer reading a page, and an all-caps usage metavar
    (``COMMAND [ARGS]...``) is the token Click itself prints -- translating
    either would change a contract instead of a label.

    Prose is recognised as a capitalised phrase of two or more words. That is
    what page chrome looks like and what an identifier, a normalisation-form
    token, a lowercase field name or a slug does not.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"))
    docstrings = {
        text
        for node in ast.walk(tree)
        if isinstance(node, ast.Module | ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
        and (text := ast.get_docstring(node, clean=False))
    }
    in_raise = {id(inner) for node in ast.walk(tree) if isinstance(node, ast.Raise) for inner in ast.walk(node)}
    # Every string inside a class that subclasses an exception: its messages are
    # developer-facing, whether raised here or passed to ``super().__init__``.
    in_exception_class = {
        id(inner)
        for node in ast.walk(tree)
        if isinstance(node, ast.ClassDef)
        and any(isinstance(base, ast.Name) and base.id.endswith(("Error", "Exception")) for base in node.bases)
        for inner in ast.walk(node)
    }
    in_dunder_all = {
        id(element)
        for node in ast.walk(tree)
        if isinstance(node, ast.Assign)
        and any(isinstance(target, ast.Name) and target.id == "__all__" for target in node.targets)
        for element in ast.walk(node)
    }
    found: list[tuple[int, str]] = []
    for node in ast.walk(tree):
        if not (isinstance(node, ast.Constant) and isinstance(node.value, str)):
            continue
        value = node.value
        if value in docstrings or id(node) in in_raise or id(node) in in_dunder_all:
            continue
        if id(node) in in_exception_class:
            continue
        if _NOT_PROSE.match(value) or value.lstrip().startswith(".."):
            continue
        # A usage metavar is Click's own token, not a label about it.
        if value.strip() and value.strip() == value.strip().upper():
            continue
        words = [word for word in value.split() if any(char.isalpha() for char in word)]
        if len(words) >= 2 and value.lstrip()[:1].isupper():
            found.append((node.lineno, value))
    return found


@pytest.mark.parametrize("generator", _GENERATORS)
def test_no_display_prose_is_hardcoded_in_the_generator(generator: str) -> None:
    """Every reader-visible string comes from the catalogues, not from source."""
    offenders = _display_literals(_REPO_ROOT / "dev" / "docs" / generator)

    assert offenders == [], (
        f"{generator} carries hardcoded display prose; author it with "
        f"`python -m dev.locales set <locale> <key> <value>` and read it through docs_chrome:\n"
        + "\n".join(f"  line {line}: {text!r}" for line, text in offenders)
    )


#: Generators whose emitted strings are held em-dash free.
#:
#: ``casilla_reference.py`` is absent DELIBERATELY and this is not a mute: it
#: emits two em dashes today, in the ``Modelo {n} - {title}`` headings at lines
#: 917 and 982, and its owner is mid-redesign on that file. Adding it here would
#: red a peer's work rather than the author's own. It goes in the moment those
#: two are fixed, and the entry below fails if this exclusion outlives them.
_EM_DASH_FREE_GENERATORS: tuple[str, ...] = (
    "legal_reference.py",
    "glossary_reference.py",
    "cli_reference.py",
    "cli_tree.py",
)

_EM_DASH = "—"


def _emitted_strings(path: Path) -> list[tuple[int, str]]:
    """String constants that reach rendered output, excluding developer prose.

    Docstrings and comments describe the code to a maintainer and never reach a
    page, so the operator's rule is enforced where it bites: on the text the
    generator actually writes.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"))
    docstrings = {
        text
        for node in ast.walk(tree)
        if isinstance(node, ast.Module | ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef)
        and (text := ast.get_docstring(node, clean=False))
    }
    return [
        (node.lineno, node.value)
        for node in ast.walk(tree)
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and node.value not in docstrings
    ]


@pytest.mark.parametrize("generator", _EM_DASH_FREE_GENERATORS)
def test_no_generator_emits_an_em_dash(generator: str) -> None:
    """No generated page carries an em dash, by operator instruction.

    Enforced on emitted strings rather than on the whole file: a maintainer's
    comment reaches no reader, and gating source-wide would fail a peer over
    prose about their own code instead of over what a taxpayer sees.
    """
    offenders = [
        (line, text) for line, text in _emitted_strings(_REPO_ROOT / "dev" / "docs" / generator) if _EM_DASH in text
    ]

    assert offenders == [], (
        f"{generator} emits an em dash; use a plain hyphen or restructure the sentence:\n"
        + "\n".join(f"  line {line}: {text!r}" for line, text in offenders)
    )


def test_the_casilla_exclusion_is_still_earned() -> None:
    """The one excluded generator is excluded for a reason that still holds.

    A stale exclusion is how an allowlist rots into a permanent hole. When the
    casilla generator stops emitting em dashes this fails, and the fix is to
    move it into the tuple above rather than to weaken this.
    """
    casilla = _REPO_ROOT / "dev" / "docs" / "casilla_reference.py"
    emitted = [(line, text) for line, text in _emitted_strings(casilla) if _EM_DASH in text]

    assert emitted, (
        "casilla_reference.py no longer emits an em dash, so its exclusion from "
        "_EM_DASH_FREE_GENERATORS is stale; add it to the tuple and delete this test"
    )


def test_the_detector_would_catch_a_reintroduced_literal() -> None:
    """The AST detector fires on a literal of exactly the shape it must catch.

    Without this, a detector that silently matched nothing would let the gate
    above pass over a generator full of English.
    """
    probe = ast.parse('def render():\n    return "Official text, in extract (in Spanish)"\n')
    literals = [
        node.value
        for node in ast.walk(probe)
        if isinstance(node, ast.Constant) and isinstance(node.value, str) and not _NOT_PROSE.match(node.value)
    ]

    assert "Official text, in extract (in Spanish)" in literals


def test_legal_chrome_changes_language_while_the_spanish_text_does_not() -> None:
    """Chrome follows the build language; the quoted Spanish never moves.

    The whole point of the surface: a reader gets the page's own words in their
    language, and the official wording exactly as Spanish law states it.
    """
    records = tuple(load_legal_provisions(_REPO_ROOT))[:40]
    rendered = {lang: render_legal_reference(_REPO_ROOT, records=records, language=lang) for lang in OutputLanguage}

    quoted_by_language = {}
    for language, result in rendered.items():
        page = result.pages[0]
        # Chrome for this language is present, and no other language's is.
        assert docs_chrome("docs.legal.record.title", language) in page.rst
        for other in OutputLanguage:
            other_title = docs_chrome("docs.legal.record.title", other)
            if other is not language and other_title != docs_chrome("docs.legal.record.title", language):
                assert other_title not in page.rst, f"{other.value} chrome leaked into the {language.value} page"
        quoted_by_language[language] = re.findall(r"<blockquote lang=\"es\">(.*?)</blockquote>", page.rst, re.DOTALL)

    assert len(set(map(tuple, quoted_by_language.values()))) == 1, (
        "the quoted Spanish legal wording differs between build languages; it must never be translated"
    )
    assert any(quoted_by_language[OutputLanguage.ES]), "no Spanish wording was quoted, so the check is vacuous"

    # The citation is Spanish content, not chrome: identical in every language.
    headings = {
        language: re.findall(r"^(.+)\n-{3,}$", result.pages[0].rst, re.MULTILINE)
        for language, result in rendered.items()
    }
    assert len(set(map(tuple, headings.values()))) == 1, "the Spanish citation changed with the build language"


def test_glossary_chrome_changes_language() -> None:
    """The glossary's own words follow the build language too."""
    handbook = load_terminology_handbook()

    for language in OutputLanguage:
        rst, _ = render_glossary(_REPO_ROOT, handbook, language)
        assert docs_chrome("docs.glossary.title", language) in rst
        for other in OutputLanguage:
            other_title = docs_chrome("docs.glossary.title", other)
            if other_title != docs_chrome("docs.glossary.title", language):
                assert other_title not in rst, f"{other.value} chrome leaked into the {language.value} glossary"


def _casilla_page(language: OutputLanguage) -> str:
    """Render one casilla page in ``language`` from constructed records.

    Deliberately not driven from the live registry projection: that projection
    refuses whenever any modelo carries an unfilled scaffold placeholder, which
    is routine while another surface is mid-authoring, and a localization gate
    that goes red on someone else's half-written catalogue reports nothing about
    localization. The records here exercise every branch that renders chrome -
    a computed casilla with a derivation, a bound one with a source, a required
    one with constraints, and a modelo overview.
    """
    common: dict[str, object] = {
        "modelo": Modelo.M130,
        "data_type": "money",
        "required": True,
        "section": ("actividades_economicas",),
        "legal_refs": ("ley-37-1992:art-92",),
        "source_refs": ("aeat-dr-130-2025",),
        "source_revisions": ("2025",),
        "descriptions": {member: f"etiqueta-{member.value}" for member in OutputLanguage},
    }
    records = (
        CasillaSearchRecord(casilla_id="01", number="01", input_kind=InputKind.BOUND, binding="b", **common),  # type: ignore[arg-type]
        CasillaSearchRecord(casilla_id="03", number="03", input_kind=InputKind.COMPUTED, formula_id="f", **common),  # type: ignore[arg-type]
    )
    schema = CompiledSchema(
        casillas={
            (Modelo.M130.value, "01"): CasillaFacts(binding_sources=("profile",)),
            (Modelo.M130.value, "03"): CasillaFacts(formula_inputs=("01",)),
        },
        modelos={
            Modelo.M130.value: ModeloOverview(
                title="IRPF pago fraccionado",
                official_name="Modelo 130. Pago fraccionado.",
                definition=None,
                tax_domain="irpf",
                cadence="quarterly",
                legal_refs=("ley-37-1992:art-92",),
            ),
        },
    )
    result = render_casilla_reference(_REPO_ROOT, records=records, language=language, schema=schema)
    return result.pages[0].rst


def test_casilla_chrome_changes_language_while_the_official_names_do_not() -> None:
    """Every display string follows the build language; the AEAT names do not.

    Checked over the whole derived key set rather than one sample key, because
    the families that render a casilla's fill provenance are exactly the ones a
    hardcoded literal would hide in.
    """
    pages = {language: _casilla_page(language) for language in OutputLanguage}

    for language, page in pages.items():
        leaked: list[str] = []
        for key in display_locale_keys():
            mine = docs_chrome(key, language)
            if len(mine) >= 6 and mine in page:
                continue
            for other in OutputLanguage:
                theirs = docs_chrome(key, other)
                if other is language or theirs == mine or len(theirs) < 6:
                    continue
                if theirs in page:
                    leaked.append(f"{key} -> {other.value}: {theirs!r}")
        assert leaked == [], f"{language.value} page carries another language's chrome:\n" + "\n".join(leaked[:10])

    # The modelo's official name and the legal citation are AEAT's own Spanish
    # and must read identically whatever language the root was built for.
    for fixed in ("Modelo 130. Pago fraccionado.", "Ley 37/1992, art. 92"):
        assert all(fixed in page for page in pages.values()), f"{fixed!r} moved with the build language"


def test_every_casilla_display_string_is_authored_in_every_language() -> None:
    """A page cannot be built in a language that has not authored its chrome."""
    missing = [
        f"{language.value}:{key}"
        for key in display_locale_keys()
        for language in OutputLanguage
        if not _is_authored(key, language)
    ]

    assert missing == [], "display strings absent from a catalogue:\n" + "\n".join(missing[:20])

    # Derived from the schema's closed value sets, so a new member arrives here
    # as a missing string rather than as silently absent copy.
    assert {f"docs.casilla.binding_source.{m.value}" for m in BindingSourceKind} <= set(display_locale_keys())


def _is_authored(key: str, language: OutputLanguage) -> bool:
    from .._locale_chrome import DocsChromeError

    try:
        docs_chrome(key, language)
    except DocsChromeError:
        return False
    return True
