"""No user-visible prose is hardcoded in the generated reference surfaces.

The defect this gate exists for renders correctly-localized CONTENT wrapped in
page CHROME that is an English literal in the generator, so a Hungarian root
ships Hungarian definitions under English headings and nothing reports it. The
gate is structural in two complementary directions, because either one alone
passes while the surface is broken.

The AST direction proves no display literal is left in the source: any string
constant reaching rendered output must come from the locale catalogues through
:func:`~dev.docs._locale_chrome.docs_chrome`. The rendered direction proves the
pages actually change language, and that the one thing which must NOT change --
the Spanish legal wording and the Spanish citation, which this layer may not
translate -- stays byte-identical across every build language.
"""

