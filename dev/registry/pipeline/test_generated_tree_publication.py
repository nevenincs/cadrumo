@pytest.mark.parametrize(
    ("defect", "error"),
    (
        ("offset", "loader semantics do not equal the current rendered layout"),
        ("length", "loader semantics do not equal the current rendered layout"),
        ("source-anchor", "field derivations do not match the rendered tree"),
        ("target-revision", "current generation authorities"),
        ("generated-file", "output-file digests"),
    ),
)
def test_publication_refuses_coordinate_authority_and_output_mutations_before_cutover(
    tmp_path,
    defect: str,
    error: str,
) -> None:
    """Every mutated candidate rejects as a whole while the live revision stays byte-identical."""
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        existing_export=True,
    )
    before_export = _tree_bytes(context.target_export_root)
    before_authority = _non_export_authority_bytes(context.target_export_root.parent)
    fragment = candidate_export_root / rendered.output_files[1]
    manifest_path = candidate_export_root / EXPORT_FRAGMENT_PROVENANCE_FILENAME

    if defect == "offset":
        original = fragment.read_bytes()
        mutated = original.replace(b"offset = 1\n", b"offset = 2\n", 1)
        assert mutated != original
        fragment.write_bytes(mutated)
    elif defect == "length":
        original = fragment.read_bytes()
        mutated = original.replace(b"length = 2\n", b"length = 3\n", 1)
        assert mutated != original
        fragment.write_bytes(mutated)
    elif defect == "source-anchor":
        manifest = load_export_fragment_provenance_manifest(manifest_path.read_bytes())
        first_derivation = manifest.field_derivations[0]
        mutated_derivation = first_derivation.model_copy(
            update={
                "parser_field": first_derivation.parser_field.model_copy(update={"source_cell": "A999"}),
                "semantic_entry": first_derivation.semantic_entry.model_copy(
                    update={
                        "anchor": first_derivation.semantic_entry.anchor.model_copy(
                            update={"source_cell": "A999"},
                        ),
                    },
                ),
            },
        )
        manifest_path.write_bytes(
            export_fragment_provenance_manifest_json_bytes(
                manifest.model_copy(
                    update={
                        "field_derivations": (mutated_derivation, *manifest.field_derivations[1:]),
                    },
                ),
            ),
        )
    elif defect == "target-revision":
        manifest = load_export_fragment_provenance_manifest(manifest_path.read_bytes())
        manifest_path.write_bytes(
            export_fragment_provenance_manifest_json_bytes(
                manifest.model_copy(update={"revision_id": "2026"}),
            ),
        )
    elif defect == "generated-file":
        fragment.write_bytes(fragment.read_bytes() + b"# candidate mutation\n")
    else:
        raise AssertionError(f"unknown candidate mutation {defect!r}")

    with pytest.raises(RegistryValidationError, match=error):
        _publish(context, joined, semantic_map, rendered)

    assert _tree_bytes(context.target_export_root) == before_export
    assert _non_export_authority_bytes(context.target_export_root.parent) == before_authority
    assert candidate_export_root.exists()
    assert not _rollback_siblings(context.target_export_root)


def test_publication_restores_live_export_after_staged_cutover_refusal(monkeypatch, tmp_path: Path) -> None:
    """A same-volume staged candidate cannot leave the old export displaced."""
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        existing_export=True,
    )
    before = _tree_bytes(context.target_export_root)
    before_authority = _non_export_authority_bytes(context.target_export_root.parent)
    real_replace = os.replace

    def refuse_staged_cutover(source: str | os.PathLike[str], destination: str | os.PathLike[str]) -> None:
        if Path(source).name.startswith(".generated-export-stage-") and Path(destination) == context.target_export_root:
            raise OSError(17, "cross-device link")
        real_replace(source, destination)

    monkeypatch.setattr(_tree_publication.os, "replace", refuse_staged_cutover)

    with pytest.raises(RegistryValidationError, match="previous target was restored"):
        _publish(context, joined, semantic_map, rendered)

    assert _tree_bytes(context.target_export_root) == before
    assert _non_export_authority_bytes(context.target_export_root.parent) == before_authority
    assert candidate_export_root.exists()
    assert not tuple(context.target_root.resolve().glob(".generated-export-stage-*"))
    assert not _rollback_siblings(context.target_export_root)
    assert not _tree_publication._journal_path(context).exists()


def test_publication_discards_only_a_completed_rollback_journal_from_an_abandoned_candidate(tmp_path: Path) -> None:
    """A prior rollback never blocks a fresh caller-owned candidate from publishing."""
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        existing_export=True,
    )
    expected_export = _tree_bytes(candidate_export_root)
    abandoned_candidate = _tree_publication._staging_sibling(
        target_root=context.target_root.resolve(),
        modelo=ISOLATED_TREE.modelo,
        revision_id=ISOLATED_TREE.revision,
    )
    backup_export_root = _tree_publication._rollback_sibling(
        target_root=context.target_root.resolve(),
        modelo=ISOLATED_TREE.modelo,
        revision_id=ISOLATED_TREE.revision,
    )
    journal = _tree_publication._PublicationJournal(
        schema_version=1,
        state="backup_staged",
        modelo=ISOLATED_TREE.modelo,
        revision_id=ISOLATED_TREE.revision,
        candidate_export=str(abandoned_candidate),
        backup_export=str(backup_export_root),
        candidate_manifest_sha256="a" * 64,
    )
    journal_path = _tree_publication._journal_path(context)
    _tree_publication._write_journal(journal_path, journal)

    published = _publish(context, joined, semantic_map, rendered)

    assert published.validated is not None
    assert _tree_bytes(context.target_export_root) == expected_export
    assert candidate_export_root.exists()
    assert not backup_export_root.exists()
    assert not journal_path.exists()


def test_publication_completes_a_real_interrupted_verified_candidate(tmp_path: Path) -> None:
    """Journal recovery completes a candidate validation had already proved before a crash."""
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        existing_export=True,
    )
    _validate(context.validation, joined, semantic_map, rendered)
    expected_export = _tree_bytes(candidate_export_root)
    before_authority = _non_export_authority_bytes(context.target_export_root.parent)
    backup_export_root = _stage_interrupted_verified_candidate(context, candidate_export_root)
    assert [path.name for path in _rollback_siblings(context.target_export_root)] == [backup_export_root.name]

    recovered = _publish(context, joined, semantic_map, rendered)

    assert recovered.validated is None
    assert _tree_bytes(context.target_export_root) == expected_export
    assert _non_export_authority_bytes(context.target_export_root.parent) == before_authority
    assert not backup_export_root.exists()
    assert not _tree_publication._journal_path(context).exists()


def _stage_interrupted_live_candidate(
    tmp_path: Path,
) -> tuple[GeneratedExportTreePublicationContext, JoinedRecordDesign, SemanticMap, RenderedExportTree, Path, Path]:
    """Stage a crash after the journaled candidate went live but before commit.

    The journal's own staged package is moved into ``export/``, exactly as the
    publication swap does. The caller's candidate export stays in place, so
    publication's candidate-path precondition passes and journal recovery runs.
    """
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        existing_export=True,
    )
    backup_export_root = _stage_interrupted_verified_candidate(context, candidate_export_root)
