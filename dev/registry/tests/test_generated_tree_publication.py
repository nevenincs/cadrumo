def _tree_bytes(root: Path) -> dict[str, bytes]:
    """Capture actual generated bytes for non-tautological filesystem assertions."""
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"), key=lambda item: item.as_posix())
        if path.is_file()
    }


def _non_export_authority_bytes(revision_root: Path) -> dict[str, bytes]:
    """Capture revision-owned TOML authority that publication must never rewrite."""
    return {
        path.relative_to(revision_root).as_posix(): path.read_bytes()
        for path in sorted(revision_root.rglob("*.toml"), key=lambda item: item.as_posix())
        if "export" not in path.relative_to(revision_root).parts
    }


def _publication_inputs(tmp_path: Path, snapshot, *, existing_export: bool, legacy_export: bool = False):
    """Build independent candidates through S08, never from a shipped tree."""
    temporary_root = tmp_path / "temporary-root"
    validation, joined, semantic_map, rendered, _candidate_export = _write_isolated_generated_authority_tree(
        temporary_root,
        snapshot,
    )
    target_root = tmp_path / "publication-root" / "registry" / "aeat"
    target_revision_root = target_root / "modelos" / "200" / "revisions" / "2025"
    target_revision_root.parent.mkdir(parents=True)
    prior = _write_isolated_generated_authority_tree(tmp_path / "prior-root", snapshot)
    prior_context = prior[0]
    prior_model_root = prior_context.registry_root / "modelos" / "200"
    os.replace(prior_model_root / "manifest.toml", target_root / "modelos" / "200" / "manifest.toml")
    prior_revision_root = prior_model_root / "revisions" / "2025"
    os.replace(prior_revision_root, target_revision_root)
    if not existing_export:
        rmtree(target_revision_root / "export")
    elif legacy_export:
        (target_revision_root / "export" / EXPORT_FRAGMENT_PROVENANCE_FILENAME).unlink()
    context = GeneratedExportTreePublicationContext(
        validation=validation,
        temporary_root=temporary_root,
        target_root=target_root,
        target_export_root=target_revision_root / "export",
    )
    candidate_export_root = validation.registry_root / "modelos" / "200" / "revisions" / "2025" / "export"
    return context, joined, semantic_map, rendered, candidate_export_root


def _rollback_siblings(target_export_root: Path) -> tuple[Path, ...]:
    target_root = target_export_root.parents[4]
    return tuple(target_root.glob(".generated-export-backup-200-2025-*"))


def test_publication_replaces_only_export_and_removes_opaque_backup(m200_snapshot, tmp_path) -> None:
    """Revision authority survives byte-identically while export+manifest cut over together."""
    context, joined, semantic_map, rendered, candidate_export_root = _publication_inputs(
        tmp_path,
        m200_snapshot,
        existing_export=True,
        legacy_export=True,
    )
    expected_export = _tree_bytes(candidate_export_root)
    revision_root = context.target_export_root.parent
    before_authority = _non_export_authority_bytes(revision_root)

    published = publish_validated_generated_export_tree(
        context=context,
        joined=joined,
        semantic_map=semantic_map,
        rendered=rendered,
    )

    assert published.export_root == context.target_export_root
    assert published.provenance_manifest_path == context.target_export_root / EXPORT_FRAGMENT_PROVENANCE_FILENAME
    assert _tree_bytes(context.target_export_root) == expected_export
    assert _non_export_authority_bytes(revision_root) == before_authority
    assert not candidate_export_root.exists()
    assert not _rollback_siblings(context.target_export_root)
    assert not (revision_root / "export.lock").exists()
    assert not _generated_tree_publication._journal_path(context).exists()


