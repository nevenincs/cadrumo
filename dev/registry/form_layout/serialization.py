"""Deterministic TOML emission of a generated form layout fragment.

The fragment is generator-owned: its bytes are a pure function of the layout,
so regeneration is idempotent and a ``--check`` run can compare bytes. Every
block, cell and placement is one inline table on one line, which keeps a
reviewer's diff to the rows that actually moved.
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Final

from cadrumo.domain.calculations.registry.schema_form_layouts import FormLayoutDefinition

__all__ = ["FORM_LAYOUT_DIRECTORY", "FORM_LAYOUT_FRAGMENT", "form_layout_fragment_path", "render_form_layout_toml"]

#: The revision section directory the loader merges into ``form_layouts``.
FORM_LAYOUT_DIRECTORY: Final[str] = "form_layouts"
FORM_LAYOUT_FRAGMENT: Final[str] = "0001-form-layout.toml"

_BARE_KEY: Final = re.compile(r"^[A-Za-z0-9_-]+$")
_OMITTED_DEFAULTS: Final[Mapping[str, object]] = {"condition": "always", "min_rows": 0}
_HEADER: Final[str] = (
    "# Generated by `python -m dev.registry.form_layout generate`; do not edit by hand.\n"
    "# Regenerate after the revision or its official record design changes.\n"
)


def form_layout_fragment_path(revision_root: Path) -> Path:
    """Return the one fragment file that holds a revision's generated layout."""
    return revision_root / FORM_LAYOUT_DIRECTORY / FORM_LAYOUT_FRAGMENT


def _key(name: str) -> str:
    return name if _BARE_KEY.fullmatch(name) else json.dumps(name, ensure_ascii=False)


def _string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def _value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, str):
        return _string(value)
    if isinstance(value, list):
        return "[" + ", ".join(_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(f"{_key(str(key))} = {_value(item)}" for key, item in value.items()) + " }"
    raise TypeError(f"form layout value {value!r} has no TOML rendering")


def _pruned(value: object) -> object:
    """Drop absent values, empty collections and the family's implicit defaults."""
    if isinstance(value, dict):
        return {
            key: _pruned(item)
            for key, item in value.items()
            if item is not None and item != [] and _OMITTED_DEFAULTS.get(key, ...) != item
        }
    if isinstance(value, list):
        return [_pruned(item) for item in value]
    return value


def _lines(table: Mapping[str, object], *, multiline: frozenset[str]) -> list[str]:
    lines: list[str] = []
    for key, value in table.items():
        if key in multiline and isinstance(value, list) and value:
            lines.append(f"{_key(key)} = [")
            lines.extend(f"    {_value(item)}," for item in value)
            lines.append("]")
        else:
            lines.append(f"{_key(key)} = {_value(value)}")
    return lines


def render_form_layout_toml(revision_id: str, layout: FormLayoutDefinition) -> str:
    """Return the fragment text declaring ``layout`` for ``revision_id``."""
    document = _pruned(layout.model_dump(mode="json"))
    if not isinstance(document, dict):
        raise TypeError("form layout did not dump to a table")
    pages = document.pop("pages", [])
    prefix = f"revisions.{_key(revision_id)}.form_layouts"
    out = [_HEADER, f"[[{prefix}]]"]
    out.extend(_lines(document, multiline=frozenset({"placements", "design_sources"})))
    for page in pages:
        sections = page.pop("sections")
        out.extend(("", f"[[{prefix}.pages]]"))
        out.extend(_lines(page, multiline=frozenset()))
        for section in sections:
            out.extend(("", f"[[{prefix}.pages.sections]]"))
            out.extend(_lines(section, multiline=frozenset({"blocks"})))
    return "\n".join(out) + "\n"
