"""Evidence for multilingual inventory and the real duplication instrument."""

from __future__ import annotations

from pathlib import Path

import pytest

from ..duplication import CloneGroup, DuplicationOutcome, DuplicationResult
from ..native_health import LanguageScope, census, inventory, scan
from ..report import Status, audit_native_language

pytestmark = [pytest.mark.integration, pytest.mark.hex_core]


@pytest.mark.parametrize(
    ("suffix", "format_name", "line"),
    [
        (".ts", "typescript", "const value{n}: number = input + {n};"),
        (".tsx", "tsx", "const value{n}: number = input + {n};"),
        (".css", "css", ".item{n} {{ padding: {n}px; margin: {n}px; color: red; }}"),
        (".rs", "rust", "let value{n}: i32 = input + {n};"),
    ],
)
def test_real_scanner_finds_copies_and_inventory_excludes_build_output(
    tmp_path: Path, suffix: str, format_name: str, line: str
) -> None:
    root = tmp_path / "source"
    root.mkdir()
    source = "\n".join(line.format(n=n) for n in range(30)) + "\n"
    (root / f"first{suffix}").write_text(source, encoding="utf-8")
    (root / f"second{suffix}").write_text(source, encoding="utf-8")
    if suffix == ".tsx":
        (root / "other.ts").write_text(source, encoding="utf-8")
    ignored = root / "target"
    ignored.mkdir()
    (ignored / f"generated{suffix}").write_text(source, encoding="utf-8")
    suffixes = (".ts", ".tsx") if suffix == ".tsx" else (suffix,)
    scope = LanguageScope(format_name, Path("source"), suffixes, format_name)

    files = inventory(tmp_path, scope)
    result = scan(tmp_path, scope)

    expected_count = 3 if suffix == ".tsx" else 2
    assert len(files) == expected_count
    assert result.outcome is DuplicationOutcome.CLONES, result.reason
    assert 2 <= result.files_analyzed <= expected_count
    assert result.raw_groups


def test_missing_or_empty_source_is_unavailable(tmp_path: Path) -> None:
    scope = LanguageScope("rust", Path("source"), (".rs",), "rust")
    assert audit_native_language(tmp_path, scope).available is False
    (tmp_path / "source").mkdir()
    result = audit_native_language(tmp_path, scope)
    assert result.status is Status.AMBER
    assert result.available is False


@pytest.mark.parametrize("analysed", [1, 2, 3])
def test_unverified_population_never_reports_green(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, analysed: int
) -> None:
    from .. import report

    scope = LanguageScope("rust", Path("source"), (".rs",), "rust")
    root = tmp_path / "source"
    root.mkdir()
    (root / "one.rs").write_text("fn one() {}", encoding="utf-8")
    (root / "two.rs").write_text("fn two() {}", encoding="utf-8")
    monkeypatch.setattr(report, "scan", lambda *_args: DuplicationResult.observed_zero(analysed))
    dimension = audit_native_language(tmp_path, scope)
    assert dimension.status is Status.AMBER
    assert not dimension.available
    assert f"2 files inventoried; {analysed} analysed" in dimension.headline
    assert any("file identities" in line for line in dimension.details)


def test_clone_evidence_survives_incomplete_coverage(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    from .. import report

    scope = LanguageScope("rust", Path("source"), (".rs",), "rust")
    root = tmp_path / "source"
    root.mkdir()
    (root / "one.rs").write_text("fn one() {}", encoding="utf-8")
    (root / "two.rs").write_text("fn two() {}", encoding="utf-8")
    clone = CloneGroup(("Clone found (rust):", " - source/one.rs [1:1 - 5:1]", " - source/two.rs [1:1 - 5:1]"))
    result = DuplicationResult.from_clones(files_analyzed=1, clone_count=1, duplicated_pct="1", groups=(clone,))
    monkeypatch.setattr(report, "scan", lambda *_args: result)
    dimension = audit_native_language(tmp_path, scope)
    assert dimension.status is Status.AMBER and not dimension.available
    assert "1 token clone(s)" in dimension.headline
    assert clone.render() in dimension.details


def test_census_distinguishes_roles_and_excludes_dependency_output(tmp_path: Path) -> None:
    paths = {
        "native/desktop/frontend/src/App.tsx": "export const app = 1;\n",
        "native/desktop/frontend/src/shell/model.ts": "// Generated by a tool; do not edit.\nexport type Model = {}\n",
        "native/desktop/frontend/tests/page.spec.ts": "test('page', () => {});\n",
        "native/desktop/frontend/src/dev/demo.ts": "export const demo = 1;\n",
        "native/desktop/frontend/src/styles/main.css": ":root {}\n",
        "native/desktop/frontend/node_modules/pkg/index.ts": "export const dependency = 1;\n",
        "native/application/src/lib.rs": (
            "//! Values generated by another process are checked here.\n"
            "use other::Value;\n/// Generated by the release owner.\npub fn run() {}\n"
        ),
        "native/application/src/tests.rs": "fn test() {}\n",
        "native/application/src/test_servers.rs": "pub fn server() {}\n",
        "native/application/fixtures/sample.rs": "fixture\n",
        "native/application/target/generated.rs": "excluded\n",
        "native/vendor/wry/src/lib.rs": "pub fn upstream() {}\n",
    }
    for name, source in paths.items():
        path = tmp_path / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(source, encoding="utf-8")
    observed = {entry.path.as_posix(): entry.role for entry in census(tmp_path)}
    assert observed == {
        "native/desktop/frontend/src/App.tsx": "runtime",
        "native/desktop/frontend/src/shell/model.ts": "generated",
        "native/desktop/frontend/tests/page.spec.ts": "test",
        "native/desktop/frontend/src/dev/demo.ts": "tooling",
        "native/desktop/frontend/src/styles/main.css": "runtime",
        "native/application/src/lib.rs": "runtime",
        "native/application/src/tests.rs": "test",
        "native/application/src/test_servers.rs": "test",
        "native/application/fixtures/sample.rs": "data",
        "native/vendor/wry/src/lib.rs": "vendored",
    }
