"""The surface redeclaration gate holds the repository at its baseline and catches each planted kind.

Every planted case runs the real scanners and ``main`` over a temporary
repository tree, so the walk, the parsing and the baseline comparison are the
ones the gate uses on the repository.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from dev.paths import REPO_ROOT

from ..surface_redeclaration import BASELINE_RELATIVE, CHECKS, baseline_text, current_keys, main

pytestmark = [pytest.mark.unit, pytest.mark.hex_core]

_WINDOW = "native/desktop/frontend/src"
_TUI = "src/cadrumo/entrypoints/tui"
_CLI = "src/cadrumo/entrypoints/cli"

_BLANK = '''def blank_to_none(text: str) -> str | None:
    """Treat a blank answer as none."""
    stripped = text.strip()
    return stripped or None
'''


def _write(root: Path, relative: str, text: str) -> None:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def _clean_tree(root: Path) -> None:
    _write(
        root,
        f"{_WINDOW}/shell/calendarContract.ts",
        "// Generated by scripts/calendar_contract.py; do not edit.\n"
        "export type FilingCalendar = { support: string };\n",
    )
    _write(root, f"{_WINDOW}/shell/views.ts", "export type ShellView = { name: string };\n")
    _write(root, f"{_WINDOW}/components/Row.tsx", "export type RowProps = { label: string };\n")
    _write(root, f"{_TUI}/home.py", _BLANK)
    _write(root, f"{_CLI}/words.py", "def words(text: str) -> str:\n    return text.upper()\n")
    _write(root, "src/cadrumo/core/text.py", "def words(text: str) -> str:\n    return text.lower()\n")


def _seal(root: Path) -> None:
    _write(root, BASELINE_RELATIVE, baseline_text(current_keys(root)))


@pytest.fixture
def tree(tmp_path: Path) -> Path:
    _clean_tree(tmp_path)
    _seal(tmp_path)
    return tmp_path


def test_the_repository_matches_its_baseline() -> None:
    assert main([], REPO_ROOT) == 0


def test_a_clean_tree_counts_only_hand_written_wire_types(tree: Path) -> None:
    found = current_keys(tree)

    # The generated contract, component props and a single-word name owned elsewhere are not counted.
    assert found["wire-type"] == {f"wire-type:{_WINDOW}/shell/views.ts:ShellView"}
    assert not found["duplicated-helper"]
    assert main([], tree) == 0


def test_a_hand_copied_wire_type_fails(tree: Path) -> None:
    _write(tree, f"{_WINDOW}/ipc/calendar.ts", "export interface FilingCalendar { support?: string }\n")

    assert main([], tree) == 1
    assert f"wire-type:{_WINDOW}/ipc/calendar.ts:FilingCalendar" in current_keys(tree)["wire-type"]


def test_a_workbench_date_decision_fails(tree: Path) -> None:
    _write(
        tree,
        f"{_TUI}/declarations/controller.py",
        "def _scope_matches(row, as_of):\n    return row.adjusted_closes_on < as_of\n",
    )

    assert main([], tree) == 1
    assert current_keys(tree)["tui-date-decision"] == {
        f"tui-date-decision:{_TUI}/declarations/controller.py:_scope_matches"
    }


def test_a_workbench_precedence_table_over_enum_members_fails(tree: Path) -> None:
    _write(
        tree,
        f"{_TUI}/sorting.py",
        "from enum import Enum\n\nclass Level(Enum):\n    HIGH = 1\n    LOW = 2\n\n"
        "_ATTENTION_RANKS = {Level.HIGH: 0, Level.LOW: 1}\n",
    )

    assert main([], tree) == 1
    assert current_keys(tree)["tui-precedence"] == {f"tui-precedence:{_TUI}/sorting.py:_ATTENTION_RANKS"}


def test_a_copied_entry_point_helper_fails(tree: Path) -> None:
    _write(tree, f"{_CLI}/answers.py", _BLANK.replace("def blank_to_none", "def _blank_to_none"))

    assert main([], tree) == 1
    assert current_keys(tree)["duplicated-helper"] == {
        f"duplicated-helper:{_TUI}/home.py:blank_to_none",
        f"duplicated-helper:{_CLI}/answers.py:blank_to_none",
    }


def test_a_helper_redefined_beside_its_shared_owner_fails(tree: Path) -> None:
    _write(tree, "src/cadrumo/core/answers.py", _BLANK.replace("stripped or None", "stripped if stripped else None"))

    assert main([], tree) == 1
    assert current_keys(tree)["duplicated-helper"] == {f"duplicated-helper:{_TUI}/home.py:blank_to_none"}


def test_a_fixed_occurrence_must_leave_the_baseline(tree: Path) -> None:
    (tree / f"{_WINDOW}/shell/views.ts").unlink()

    assert main([], tree) == 1
    assert main(["--write-baseline"], tree) == 0
    assert main([], tree) == 0
    document = json.loads((tree / BASELINE_RELATIVE).read_text(encoding="utf-8"))
    assert document["counts"] == dict.fromkeys(CHECKS, 0)


def test_the_baseline_refuses_to_grow(tree: Path) -> None:
    before = (tree / BASELINE_RELATIVE).read_text(encoding="utf-8")
    _write(tree, f"{_WINDOW}/shell/ledger.ts", "export type LedgerRow = { id: string };\n")

    assert main(["--write-baseline"], tree) == 1
    assert (tree / BASELINE_RELATIVE).read_text(encoding="utf-8") == before
