"""The TypeScript module-size gate finds every module over its bound, wherever it lives.

Each planted case runs the real gate over a temporary repository tree, so the
walk, the ignore rules and the line measurement are the ones the gate uses.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from dev.paths import REPO_ROOT

from ..typescript_module_size import MAX_PHYSICAL_LINES, TYPESCRIPT_SUFFIXES, main, oversized, typescript_modules

pytestmark = [pytest.mark.unit, pytest.mark.hex_core]

_DESKTOP = "native/desktop"


def test_no_typescript_module_in_the_repository_exceeds_the_bound() -> None:
    modules = typescript_modules(REPO_ROOT)

    # The walk reaches product code, generated contracts, specs and scripts.
    assert f"{_DESKTOP}/frontend/src/main.tsx" in modules
    assert f"{_DESKTOP}/frontend/src/shell/modeloContract/contracts.ts" in modules
    assert f"{_DESKTOP}/frontend/playwright.config.ts" in modules
    assert any(Path(relative).parent.as_posix() == f"{_DESKTOP}/scripts" for relative in modules)
    found = oversized(REPO_ROOT)
    assert not found, "\n".join(f"{path}: {lines} physical lines (bound {MAX_PHYSICAL_LINES})" for path, lines in found)


def _plant(root: Path, relative: str, lines: int, *, newline: str = "\n", final: bool = True) -> Path:
    path = root / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    body = newline.join(f"export const line{index} = {index};" for index in range(lines))
    path.write_bytes((body + (newline if final else "")).encode())
    return path


@pytest.mark.parametrize("suffix", sorted(TYPESCRIPT_SUFFIXES))
def test_a_module_one_line_over_the_bound_is_found(tmp_path: Path, suffix: str) -> None:
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/big{suffix}", MAX_PHYSICAL_LINES + 1)

    assert oversized(tmp_path) == [(f"{_DESKTOP}/frontend/src/big{suffix}", MAX_PHYSICAL_LINES + 1)]


def test_a_module_at_the_bound_passes(tmp_path: Path) -> None:
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/edge.tsx", MAX_PHYSICAL_LINES)

    assert oversized(tmp_path) == []
    assert main(tmp_path) == 0


def test_the_command_fails_on_a_module_over_the_bound(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/edge.tsx", MAX_PHYSICAL_LINES)
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/big.ts", MAX_PHYSICAL_LINES + 1)

    assert main(tmp_path) == 1
    assert f"{_DESKTOP}/frontend/src/big.ts: {MAX_PHYSICAL_LINES + 1} physical lines" in capsys.readouterr().out


@pytest.mark.parametrize(
    ("newline", "final"),
    [("\n", False), ("\r\n", True), ("\r\n", False), ("\r", True)],
    ids=["no-final", "crlf", "crlf-no-final", "lone-cr"],
)
def test_line_endings_and_a_missing_final_newline_do_not_hide_a_line(tmp_path: Path, newline: str, final: bool) -> None:
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/big.ts", MAX_PHYSICAL_LINES + 1, newline=newline, final=final)

    assert oversized(tmp_path) == [(f"{_DESKTOP}/frontend/src/big.ts", MAX_PHYSICAL_LINES + 1)]


@pytest.mark.parametrize("separator", ["\u2028", "\u2029", "\v", "\f", "\x85"], ids=["ls", "ps", "vt", "ff", "nel"])
def test_only_line_feeds_and_carriage_returns_end_a_line(tmp_path: Path, separator: str) -> None:
    path = tmp_path / _DESKTOP / "frontend/src/text.ts"
    path.parent.mkdir(parents=True)
    lines = [f'export const line{index} = "a{separator}b";' for index in range(MAX_PHYSICAL_LINES)]
    path.write_bytes(("\n".join(lines) + "\n").encode())

    assert oversized(tmp_path) == []
    path.write_bytes(path.read_bytes() + b"export const extra = 1;\n")
    assert oversized(tmp_path) == [(f"{_DESKTOP}/frontend/src/text.ts", MAX_PHYSICAL_LINES + 1)]


def test_blank_lines_and_comments_count(tmp_path: Path) -> None:
    path = tmp_path / _DESKTOP / "frontend/src/padded.ts"
    path.parent.mkdir(parents=True)
    lines = ["// note" if index % 2 else "" for index in range(MAX_PHYSICAL_LINES)]
    path.write_text("export const kept = 1;\n" + "\n".join(lines) + "\n", encoding="utf-8")

    assert oversized(tmp_path) == [(f"{_DESKTOP}/frontend/src/padded.ts", MAX_PHYSICAL_LINES + 1)]


def test_a_generated_module_is_held_to_the_bound(tmp_path: Path) -> None:
    path = _plant(tmp_path, f"{_DESKTOP}/frontend/src/shell/contract.ts", MAX_PHYSICAL_LINES)
    path.write_text("// Generated by a script; do not edit.\n" + path.read_text(encoding="utf-8"), encoding="utf-8")

    assert oversized(tmp_path) == [(f"{_DESKTOP}/frontend/src/shell/contract.ts", MAX_PHYSICAL_LINES + 1)]


def test_specs_stories_prototypes_and_scripts_are_held_to_the_bound(tmp_path: Path) -> None:
    planted = [
        f"{_DESKTOP}/frontend/tests/scenarios/big.spec.ts",
        f"{_DESKTOP}/frontend/src/components/Big.stories.tsx",
        f"{_DESKTOP}/frontend/src/dev/prototypes/ledger/Big.tsx",
        f"{_DESKTOP}/scripts/big.mts",
    ]
    for relative in planted:
        _plant(tmp_path, relative, MAX_PHYSICAL_LINES + 1)

    assert [path for path, _ in oversized(tmp_path)] == sorted(planted)


def test_a_module_under_any_other_root_is_held_to_the_bound(tmp_path: Path) -> None:
    planted = ["docs/_static/widget.ts", "dev/tools/probe.cts", "native/manager/ui/view.tsx", "root.ts"]
    for relative in planted:
        _plant(tmp_path, relative, MAX_PHYSICAL_LINES + 1)

    assert [path for path, _ in oversized(tmp_path)] == sorted(planted)


def test_ignored_files_and_other_languages_are_not_measured(tmp_path: Path) -> None:
    (tmp_path / ".gitignore").write_text("node_modules/\nbuild/\n", encoding="utf-8")
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/main.ts", 1)
    _plant(tmp_path, f"{_DESKTOP}/frontend/node_modules/library/index.d.ts", MAX_PHYSICAL_LINES * 3)
    _plant(tmp_path, "build/bundle.ts", MAX_PHYSICAL_LINES * 3)
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/data.json", MAX_PHYSICAL_LINES * 3)
    _plant(tmp_path, f"{_DESKTOP}/frontend/src/main.js", MAX_PHYSICAL_LINES * 3)

    assert oversized(tmp_path) == []
    assert main(tmp_path) == 0


def test_a_tree_without_typescript_is_refused_rather_than_read_as_clean(tmp_path: Path) -> None:
    _plant(tmp_path, "src/main.py", 1)

    assert main(tmp_path) == 1
