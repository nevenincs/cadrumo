"""Assemble the Cadrumo MCP console as an ``.mcpb`` Desktop Extension bundle.

SECONDARY (but self-installing) ARTIFACT. The Claude plugin — generated by
``aeat app agent --layout plugin`` and served from the marketplace tree under
``packaging/marketplace/`` — is the primary consumer distribution path. This
``.mcpb`` bundle is the classic-Desktop path, and it now boots the SAME way the
plugin does: its ``server.mcp_config`` launches
``uvx --from cadrumo[agent]==<version> cadrumo-mcp``, so opening the bundle in
Claude Desktop self-installs the Cadrumo Python package (with the ``[agent]``
extra the MCP SDK rides) from PyPI on first run — the host needs only ``uv`` on
PATH, NOT a prior ``pip install cadrumo[agent]``. The server still runs locally;
a remote-hosted server would defeat the on-host-data posture.

Version single-sourcing: the bundle version and the ``uvx`` pin are STAMPED from
the root ``pyproject.toml`` at build time, exactly as the plugin stamps its
``.mcp.json`` pin from the package version, so a release bump can never ship a
bundle pinned to a stale release. The committed manifest carries the same version
and is held to it by the release-readiness ``version-surfaces-agree`` gate and the
tests here.

This script is deliberately dependency-light (stdlib only; it never imports the
``cadrumo`` package): it validates the manifest, stamps the version pin, stages
it, and zips the ``.mcpb`` (a zip with a ``.mcpb`` extension, per the Desktop
Extension format). SIGNING is honest: the bundle is signed only when a signing
identity is actually available (the ``mcpb`` CLI plus a configured certificate);
absent that, the script emits an UNSIGNED bundle and says so plainly — it never
fabricates a signature. This builder proves archive assembly, not Desktop
installation or publisher verification; signing remains an operator release step,
not a build-time fake.

Run it as a script (the repo-root ``packaging/`` directory intentionally shadows
nothing importable — the name collides with the installed PyPA ``packaging``
library, so this is never imported as ``packaging.mcpb``)::

    python packaging/mcpb/build.py            # build dist/cadrumo.mcpb (unsigned unless mcpb+identity present)
    python packaging/mcpb/build.py --check     # validate the manifest only, write nothing
"""

from __future__ import annotations

import argparse
import json
import shutil
import subprocess
import sys
import tomllib
import zipfile
from pathlib import Path
from typing import cast

_HERE = Path(__file__).resolve().parent
_MANIFEST = _HERE / "manifest.json"
_PYPROJECT = _HERE.parents[1] / "pyproject.toml"
_REQUIRED_TOP_LEVEL = ("manifest_version", "name", "version", "description", "server")
_REQUIRED_SERVER = ("type", "mcp_config")
# The bundle self-installs via ``uvx --from <distribution>[agent]==<version>
# <console-script>``. These identity strings are the Cadrumo product identity;
# they are duplicated here as literals rather than imported (this builder never
# imports the ``cadrumo`` package — see the module docstring), and the parity
# test asserts they match ``cadrumo.core.product_identity.PRODUCT_IDENTITY``.
_MCP_LAUNCHER = "uvx"
_DISTRIBUTION = "cadrumo"
_CONSOLE_SCRIPT = "cadrumo-mcp"


class ManifestError(ValueError):
    """Raised when the bundle manifest is missing a required field."""


def _package_version() -> str:
    """Return the single-source package version from the root ``pyproject.toml``.

    This is the same authority the release-readiness ``version-surfaces-agree``
    gate treats as canonical; the plugin generator reads the installed
    distribution metadata (which is stamped from this same value).
    """
    return str(tomllib.loads(_PYPROJECT.read_text(encoding="utf-8"))["project"]["version"])


def _uvx_args(version: str) -> list[str]:
    """Return the ``uvx`` self-install bootstrap args pinned to ``version``."""
    return ["--from", f"{_DISTRIBUTION}[agent]=={version}", _CONSOLE_SCRIPT]


def load_manifest() -> dict[str, object]:
    """Load and validate ``manifest.json`` against the required-field contract."""
    data = json.loads(_MANIFEST.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise ManifestError("manifest.json must be a JSON object")
    missing = [key for key in _REQUIRED_TOP_LEVEL if key not in data]
    if missing:
        raise ManifestError(f"manifest.json missing required fields: {', '.join(missing)}")
    server = data["server"]
    if not isinstance(server, dict) or any(key not in server for key in _REQUIRED_SERVER):
        raise ManifestError("manifest.json 'server' must carry 'type' and 'mcp_config'")
    mcp_config = server["mcp_config"]
    if not isinstance(mcp_config, dict) or "command" not in mcp_config:
        raise ManifestError("manifest.json 'server.mcp_config' must carry a 'command'")
    if mcp_config["command"] != _MCP_LAUNCHER:
        raise ManifestError(
            f"manifest.json 'server.mcp_config.command' must be {_MCP_LAUNCHER!r} so the bundle self-installs "
            f"the {_DISTRIBUTION}[agent] package from PyPI; got {mcp_config['command']!r}",
        )
    args = mcp_config.get("args")
    if not isinstance(args, list) or _CONSOLE_SCRIPT not in args or f"{_DISTRIBUTION}[agent]==" not in "".join(
        part for part in args if isinstance(part, str)
    ):
        raise ManifestError(
            f"manifest.json 'server.mcp_config.args' must be the uvx bootstrap "
            f"['--from', '{_DISTRIBUTION}[agent]==<version>', '{_CONSOLE_SCRIPT}']; got {args!r}",
        )
    return data


def stamped_manifest() -> dict[str, object]:
    """Return the manifest with its version and ``uvx`` pin stamped from pyproject.

    Single-sources the shipped version the same way the plugin stamps its
    ``.mcp.json`` pin: the bundle version and the ``uvx --from ...==<version>``
    pin are set from the root ``pyproject.toml`` at build time, so a release bump
    can never ship a bundle pinned to a stale release.
    """
    data = load_manifest()
    version = _package_version()
    data["version"] = version
    # ``load_manifest`` already validated the server / mcp_config / args shape; the
    # casts make the nested mutation explicit for the type checker.
    server = cast("dict[str, object]", data["server"])
    mcp_config = cast("dict[str, object]", server["mcp_config"])
    mcp_config["args"] = _uvx_args(version)
    return data


def _signing_available() -> bool:
    """Return whether the ``mcpb`` CLI is on PATH so signing can be attempted."""
    return shutil.which("mcpb") is not None


def _sign(bundle: Path) -> bool:
    """Sign ``bundle`` with the ``mcpb`` CLI; return True only on a real success.

    Never fabricates a signature: if the CLI is absent or signing fails (no
    configured identity), it reports and returns False, leaving the unsigned
    bundle in place.
    """
    if not _signing_available():
        return False
    completed = subprocess.run(  # noqa: S603
        ["mcpb", "sign", str(bundle)],  # noqa: S607
        capture_output=True,
        text=True,
        check=False,
        stdin=subprocess.DEVNULL,
    )
    if completed.returncode != 0:
        sys.stderr.write(f"mcpb sign failed (no identity?); shipping unsigned:\n{completed.stderr}\n")
        return False
    return True


def build(*, dist_dir: Path | None = None) -> Path:
    """Build ``dist/cadrumo.mcpb`` from the version-stamped manifest, return its path."""
    manifest = stamped_manifest()
    dist = dist_dir if dist_dir is not None else _HERE.parents[1] / "dist"
    dist.mkdir(parents=True, exist_ok=True)
    bundle = dist / "cadrumo.mcpb"
    with zipfile.ZipFile(bundle, "w", zipfile.ZIP_DEFLATED) as archive:
        archive.writestr("manifest.json", json.dumps(manifest, indent=2, ensure_ascii=False))
    signed = _sign(bundle)
    state = "signed" if signed else "UNSIGNED (signer unavailable or no signing identity configured)"
    sys.stdout.write(f"built {bundle} [{state}]\n")
    return bundle


def main(argv: list[str] | None = None) -> int:
    """CLI entry: ``--check`` validates the manifest; default builds the bundle."""
    parser = argparse.ArgumentParser(description="Build the Cadrumo .mcpb Desktop Extension.")
    parser.add_argument("--check", action="store_true", help="Validate the manifest only; write nothing.")
    args = parser.parse_args(argv)
    try:
        manifest = load_manifest()
    except ManifestError as exc:
        sys.stderr.write(f"manifest invalid: {exc}\n")
        return 1
    if args.check:
        sys.stdout.write(f"manifest.json valid: {manifest['name']} {manifest['version']}\n")
        return 0
    build()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
